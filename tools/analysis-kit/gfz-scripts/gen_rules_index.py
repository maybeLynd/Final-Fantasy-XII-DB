#!/usr/bin/env python3
"""gen_rules_index.py - harvest every established rule into one navigable index.

Why generated and not written
-----------------------------
The rules live in about a dozen files and run to some four thousand lines: the evidence standard,
the coverage log's instrument findings, the mission prompt, the tool contracts, the coordination
protocol, the templates and the checker docstrings. **Nobody can hold that, and a hand-written
summary of it would be stale within a day** -- which is exactly what `EVIDENCE-STANDARD.md` says
under *"hand-maintained indexes drift; check them mechanically."*

So this is an INDEX, never a copy. It names each rule and points at the file that owns it. **The
source file is always authoritative**; if this disagrees with it, this is wrong. Regenerate rather
than edit, and never paste a rule's text in here -- two copies of a rule is one rule and one
decoy.

What counts as a rule
---------------------
A `##`/`###` heading in a canonical rules file. That is a deliberately mechanical definition: it
cannot be argued with, and it cannot quietly omit a rule somebody found inconvenient. The cost is
that a few headings are structural rather than normative ("Where everything is"), and those are
left in rather than filtered by taste.

Usage
-----
    python gen_rules_index.py --root <repo root> --out "Database/FFXII TZA/_index/RULES.md"
    python gen_rules_index.py --self-test
"""
import argparse
import ast
import io
import os
import re
import sys

HEADING = re.compile(r"^(#{2,3})\s+(.*?)\s*$")

# (path relative to repo root, section title, one-line note on what this file governs)
SOURCES = [
    ("Database/FFXII TZA/_index/EVIDENCE-STANDARD.md", "Evidence and method",
     "What counts as proof, what is banned, and how a claim earns the right to be called fact."),
    ("Database/GFZ-MISSION-PROMPT.md", "The mission and the loop",
     "What the database is for, the work loop, and the non-negotiables."),
    ("Database/FFXII TZA/_index/COMPLETION-PLAN.md", "Completion and scope",
     "What done means, the A/B/C dispositions, and what is deliberately out of scope."),
    ("Database/FFXII TZA/_index/_inbox/README.md", "Working as a team",
     "Coordination protocol: authority, inboxes, question ids, concurrent-edit hazards."),
    ("Database/FFXII TZA/_index/_inbox/TEAM.md", "The three-agent operating model",
     "FABLE, OPUS, ASTRA: claims, handoffs, publication, runtime ownership and continuation."),
    ("Database/Tools/README.md", "Tooling contracts",
     "Script argument contracts, the hash-convention trap, and what is banned."),
    ("Database/FFXII TZA/_index/FINAL-AUDIT-PROTOCOL.md", "The terminal gate",
     "The thirty-pass final audit. Gated; not startable early."),
    ("Database/FFXII TZA/_templates/SYSTEM.md", "Writing a system document",
     "Section shape for a SYSTEM sheet."),
    ("Database/FFXII TZA/_templates/FORMAT.md", "Writing a format sheet",
     "Section shape for a FORMAT sheet: corpus validation first, loader contract at the centre."),
    ("Database/FFXII TZA/_index/COVERAGE.md", "Instrument findings — how measurement goes wrong",
     "Every way a census, scan or metric has misled this project, with the case that proved it."),
]

SCRIPT_DIR = "Database/Tools/analysis-kit/gfz-scripts"


def anchor(text):
    """GitHub-style heading slug."""
    s = text.lower()
    s = re.sub(r"[`*_\[\]()]", "", s)
    s = re.sub(r"[^a-z0-9\s-]", "", s)
    return re.sub(r"\s+", "-", s.strip())


def headings(path):
    out = []
    for line in io.open(path, encoding="utf-8", errors="replace"):
        m = HEADING.match(line.rstrip("\n"))
        if m:
            out.append((len(m.group(1)), m.group(2)))
    return out


def script_rules(root):
    """(script, first docstring line) for each checker - each encodes one rule."""
    d = os.path.join(root, SCRIPT_DIR)
    out = []
    for fn in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if not fn.endswith(".py"):
            continue
        with io.open(os.path.join(d, fn), encoding="utf-8-sig") as stream:
            txt = stream.read()
        doc = ast.get_docstring(ast.parse(txt, filename=fn))
        if doc:
            out.append((fn, doc.splitlines()[0].strip()))
    return out


def build(root):
    L = ["# The rules — one index, generated",
         "",
         "**Generated by `gen_rules_index.py`. Do not edit; regenerate.**",
         "",
         "This names every established rule and points at the file that owns it. **It is an index,",
         "never a copy** — the source file is always authoritative, and if this disagrees with one,",
         "this is wrong. Rules are not restated here on purpose: *two copies of a rule is one rule",
         "and one decoy.*",
         "",
         "> **New to the project?** Read [the mission](../../GFZ-MISSION-PROMPT.md) and",
         "> [the evidence standard](EVIDENCE-STANDARD.md) in full before anything else. Everything",
         "> below assumes both.",
         ""]
    total = 0
    for rel, title, note in SOURCES:
        p = os.path.join(root, rel)
        if not os.path.isfile(p):
            L += ["## %s" % title, "", "*(missing: `%s`)*" % rel, ""]
            continue
        hs = headings(p)
        total += len(hs)
        # link from _index/ to the source
        link = os.path.relpath(p, os.path.join(root, "Database/FFXII TZA/_index")).replace(os.sep, "/")
        L += ["## %s" % title, "", "%s" % note, "",
              "**Source: [`%s`](%s)** — %d entries, %d lines." %
              (os.path.basename(rel), link, len(hs), sum(1 for _ in io.open(p, encoding="utf-8", errors="replace"))),
              ""]
        for lvl, h in hs:
            L.append("%s- [%s](%s#%s)" % ("  " * (lvl - 2), h, link, anchor(h)))
        L.append("")

    sr = script_rules(root)
    L += ["## Checkers — each encodes a rule mechanically", "",
          "A rule nobody can enforce is a preference. These are the ones with teeth: each script "
          "fails\nthe build rather than asking politely.", "",
          "| script | what it enforces |", "|---|---|"]
    for fn, doc in sr:
        L.append("| `%s` | %s |" % (fn, doc.replace("|", "\\|")))
    L += ["", "---", "",
          "**%d rule headings across %d documents, plus %d checkers.**" % (total, len(SOURCES), len(sr)),
          "",
          "The count is not a boast. It is the reason this index is generated: **nobody can hold",
          "that many rules in their head, and a summary somebody maintains by hand would be stale",
          "within a day.**", ""]
    return "\n".join(L)


def refuse_to_destroy(out, new_text, force, what):
    """Exit 3 rather than write a stub over a canonical file. -> None, or raises SystemExit(3).

    `os.walk` on a path that does not exist yields nothing and raises nothing, so a wrong argument
    and an empty corpus look identical from inside. This tool wrote 1,908 bytes over 148,793 at
    exit 0 when given a `--root` that does not exist; ec044d8f is what that looks like once it is
    committed. Not a quality threshold: drift in both directions passes untouched.
    """
    import sys
    if force or not os.path.isfile(out):
        return
    try:
        had = len(io.open(out, encoding="utf-8", errors="replace").read())
    except OSError:
        return
    if had and len(new_text) * 2 < had:
        sys.stderr.write(
            "REFUSING TO WRITE: %s holds %d bytes of %s and this run produced %d - less than\n"
            "half. A regeneration that empties a canonical file is a defect in the run, not news\n"
            "about the corpus. If the shrink is real, pass --force.\n" % (out, had, what, len(new_text)))

        raise SystemExit(3)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--root")
    ap.add_argument("--out")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--force", action="store_true",
                    help="write even if the result is under half the size of the file it replaces")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    if not (a.root and a.out):
        return ap.error("--root and --out required")
    # A WRONG --root IS SILENT. os.walk yields nothing for a path that does not exist, so the
    # index of every rule in the kit becomes a header. Measured: 148,793 bytes -> 1,908, exit 0.
    if not os.path.isdir(a.root):
        sys.stderr.write("REFUSING: --root %s is not a directory. An index of no rules is a wrong\n"
                         "argument, not a kit without rules.\n" % a.root)
        return 3
    text = build(a.root)
    if text.count("\n|") < 2:
        sys.stderr.write("REFUSING: no rules found under %s - a wrong --root, not a kit without\n"
                         "rules. Nothing was written.\n" % a.root)
        return 3
    refuse_to_destroy(a.out, text, a.force, "rules index")
    io.open(a.out, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s" % a.out)
    return 0


def self_test():
    ok = True
    if anchor("Never edit a provenance stamp to make a check pass") != \
            "never-edit-a-provenance-stamp-to-make-a-check-pass":
        print("SELF-TEST FAILED: anchor %s" % anchor("Never edit a provenance stamp to make a check pass")); ok = False
    if anchor("A `metric` that returns its value (by construction)") != \
            "a-metric-that-returns-its-value-by-construction":
        print("SELF-TEST FAILED: punctuation anchor %s"
              % anchor("A `metric` that returns its value (by construction)")); ok = False
    hs = HEADING.match("### Tier 10 has no caveat")
    if not hs or len(hs.group(1)) != 3:
        print("SELF-TEST FAILED: heading level"); ok = False
    if HEADING.match("# Title") or HEADING.match("#### Deep"):
        print("SELF-TEST FAILED: level filter accepted # or ####"); ok = False
    if not ok:
        return 1
    print("self-test ok: anchors slugged, backticks and parentheses stripped, only ## and ### "
          "counted as rules")
    return 0


if __name__ == "__main__":
    sys.exit(main())
