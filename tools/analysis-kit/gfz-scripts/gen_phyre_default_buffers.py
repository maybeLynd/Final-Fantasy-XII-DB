#!/usr/bin/env python3
"""gen_phyre_default_buffers.py - the THREE per-class scratch buffers, from the registering calls.

WHAT THE STORE HAD. `phyre-default-instances.tsv` records ONE buffer per class for 173 classes,
the pointer installed at `descriptor+0xC0` by the one-instruction setter `0063DC80`.

WHAT THE IMAGE HAS. `0063DC80`, `0063DF90` and `0063DFA0` are three consecutive one-instruction
setters - `mov [rcx+0xC0], rdx`, `mov [rcx+0xC8], rdx`, `mov [rcx+0xD0], rdx` - and each is
called from 384 bodies. Every class that registers one registers all three. The descriptor
constructor `00632D80` nulls all three at `00632E16`/`00632E1D`/`00632E24` before they are set,
so they are one family and not three unrelated slots.

WHY THREE, from the engine's own diagnostic text. `00639A60` memsets the `+0xC8` buffer and the
`+0xC0` buffer to 0xA5, default-constructs an object into each through vtable slot `+0x50`, and
memcmps them. On a mismatch it prints:

    "Class '%s' has a position dependant constructor and should be marked as having no default
     constructor to avoid usage of the default buffer"                             (00D584A0)

So `+0xC0` is the DEFAULT BUFFER - the engine's own term - and `+0xC8` is the second construction
used only to prove the constructor does not depend on the address it is built at. `+0xD0` is
registered identically and no reader of it is identified here; that is left as an open slot
rather than guessed at.

HOW EACH ROW IS RECOVERED, all from ONE body - the class's descriptor constructor:
  * the class NAME from `lea r8,[rdata]` at the `call 00632D80`, read as a C string;
  * the INSTANCE SIZE from the `mov r9d, imm` at the same call - the same number the descriptor
    stores at `+0x38` and the same one the memsets and memcpys use as their length;
  * the three BUFFERS from `lea rdx,[data]` at each of the three setter calls.
The descriptor address is NOT recovered here and is deliberately left out: these constructors
take `this` as an ARGUMENT (`mov rbx,rcx` at the top), so the descriptor address is lea'd by the
caller, and a column filled from a different body is a column that can be filled from the wrong
body. `phyre-default-instances.tsv` already carries the descriptor for the classes it covers.

CONTROLS.
  * PDeferredLightingBase, whose constructor 006442E0 is read by hand in the page: expect
    0x41D8 / 02CF9970 / 02CFDB50 / 02D01D30.
  * All 173 rows of phyre-default-instances.tsv must reappear with the same `+0xC0` buffer. A
    generator that recovers a superset but disagrees with the established subset is wrong about
    the subset, not right about the superset.

CONTIGUITY IS REPORTED, NOT ASSUMED. Most classes get three buffers laid out back to back at a
stride of the instance size rounded up, but not all of them do, so each row carries the two
strides and says whether they are equal. Twenty of the 384 are not evenly spaced and nothing here
explains why; calling them contiguous because most are would be the thing this database keeps
catching itself doing.

usage: gen_phyre_default_buffers.py [--out <tsv>] [--check]
"""
import argparse
import collections
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check_absence_claims as G  # noqa: E402
import call_graph as CG  # noqa: E402
import check_default_instance_writers as W  # noqa: E402

import capstone  # noqa: E402
from capstone.x86 import X86_OP_IMM, X86_OP_REG  # noqa: E402

X = capstone.x86
SETTERS = {0x0063DC80: "b_C0", 0x0063DF90: "b_C8", 0x0063DFA0: "b_D0"}
CTORS = (0x00632D80, 0x00632C90)
CONTROL = ("PDeferredLightingBase", 0x41D8, 0x02CF9970, 0x02CFDB50, 0x02D01D30)

OUT = ("22-Middleware-PhyreEngine/Reflection-And-Class-Metadata/members/"
       "phyre-class-default-buffers.tsv")

HEADER = """\
# The three per-class scratch buffers a Phyre class descriptor registers, and the size they are
# registered with. Generated by Tools/analysis-kit/gfz-scripts/gen_phyre_default_buffers.py from
# the shipping image; every field comes from the class's own descriptor constructor.
#
# b_C0 is THE DEFAULT BUFFER (the engine's term, from the diagnostic string at 00D584A0): the
# object PCluster::create memcpy's every new instance from, at 0063C974. It is BUILT AT RUNTIME
# by 00639A60 - memset 0xA5, default-construct through vtable +0x50, memcpy - not authored into
# the image. b_C8 is the second construction used to detect a position-dependent constructor.
# b_D0 is registered by the same family and no reader of it is identified.
#
# size is the instance size passed to the descriptor constructor in r9d and stored at
# descriptor+0x38; it is the length of every memset and memcpy over these buffers.
# stride_C8 = b_C8 - b_C0, stride_D0 = b_D0 - b_C8, even = the two are equal.
#
# 69 of the 384 rows read UNRECOVERED for class and size. Those bodies are guard-protected
# thread-safe static initialisers (a TLS guard read through gs:[0x58], then a branch), and a
# straight-line read of them does not reach the constructor call that carries the name and the
# size. THEIR THREE BUFFERS ARE STILL RECOVERED, because the three setter calls are reached; the
# inventory of buffers is complete at 384 classes, the inventory of NAMES is 315 of 384.
#
# ctor_body is the descriptor constructor every field on the row was read from. exe
# 73461d0896204b1c259c52f61aef4efbc95a2ffc388cadb36493d5d1d89721f8
"""


def cstring(img, addr, n=128):
    b = img.read(addr, n)
    if not b:
        return None
    b = b.split(bytes([0]))[0]
    if not b or len(b) == n:
        return None
    try:
        s = b.decode("ascii")
    except UnicodeDecodeError:
        return None
    return s if all(32 <= ord(c) < 127 for c in s) else None


def recover(img):
    callers, _c, _s = CG.call_maps(G.EXE, G.FUNCS)
    hosts = set()
    for t in SETTERS:
        hosts |= set(callers.get(t, ()))
    rows, partial = [], 0
    for h in sorted(hosts):
        held, name, size, bufs = {}, None, None, {}
        for i in img.body(h):
            v = W.lea_value(i)
            if v is not None:
                held[W.norm(i.operands[0].reg)] = v
                continue
            if (i.mnemonic == "mov" and len(i.operands) == 2
                    and i.operands[0].type == X86_OP_REG):
                d = W.norm(i.operands[0].reg)
                s = i.operands[1]
                if s.type == X86_OP_REG and W.norm(s.reg) in held:
                    held[d] = held[W.norm(s.reg)]
                elif s.type == X86_OP_IMM:
                    held[d] = ("imm", s.imm)
                else:
                    held.pop(d, None)
                continue
            if i.mnemonic == "call" and i.operands and i.operands[0].type == X86_OP_IMM:
                t = i.operands[0].imm
                if t in CTORS:
                    nm = held.get(X.X86_REG_R8)
                    if isinstance(nm, int):
                        name = cstring(img, nm)
                    sz = held.get(X.X86_REG_R9)
                    if isinstance(sz, tuple):
                        size = sz[1]
                elif t in SETTERS:
                    b = held.get(X.X86_REG_RDX)
                    if isinstance(b, int):
                        bufs[SETTERS[t]] = b
                held = {k: x for k, x in held.items() if k not in W.VOLATILE}
                continue
            try:
                _r, w = i.regs_access()
            except capstone.CsError:
                w = []
            for r in w:
                held.pop(W.norm(r), None)
            if i.mnemonic == "call":
                held = {k: x for k, x in held.items() if k not in W.VOLATILE}
        if len(bufs) == 3:
            if not (name and size):
                partial += 1
            rows.append((name or "UNRECOVERED", size or 0,
                         bufs["b_C0"], bufs["b_C8"], bufs["b_D0"], h))
        else:
            partial += 1
    return rows, len(hosts), partial


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(G.DB, OUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    img = W.Image()
    rows, hosts, partial = recover(img)
    rows.sort()
    print("bodies calling a buffer setter            : %d" % hosts)
    print("rows with all three buffers               : %d" % len(rows))
    print("  of those, class name + size recovered   : %d"
          % sum(1 for r in rows if r[0] != "UNRECOVERED"))
    print("  name/size NOT recovered                 : %d" % partial)

    got = {r[0]: r for r in rows}
    c = CONTROL
    ok = c[0] in got and tuple(got[c[0]][1:5]) == tuple(c[1:])
    print("CONTROL PDeferredLightingBase             : %s"
          % ("PASS" if ok else "FAIL  got %r" % (got.get(c[0]),)))

    store = W.default_instances(G.DB)
    bymine = {r[2] for r in rows}
    missing = set(store) - bymine
    print("CONTROL all 173 established +0xC0 buffers : %s   (%d missing)"
          % ("PASS" if not missing else "FAIL", len(missing)))
    print("new +0xC0 buffers beyond the store's 173  : %d" % len(bymine - set(store)))
    rows = [r for r in rows if r[0] != "UNRECOVERED"] +            sorted(r for r in rows if r[0] == "UNRECOVERED")
    uneven = [r for r in rows if (r[3] - r[2]) != (r[4] - r[3])]
    print("classes whose three buffers are NOT evenly spaced: %d" % len(uneven))
    pad = collections.Counter((r[3] - r[2]) - r[1] for r in rows
                              if (r[3] - r[2]) == (r[4] - r[3]) and r[1])
    print("even-stride padding over the instance size:",
          dict(sorted(pad.items(), key=lambda kv: -kv[1])[:6]))
    if not ok or missing:
        print("A CONTROL FAILED -> the table is not written.")
        return 2
    if a.check:
        return 0

    with io.open(a.out, "w", encoding="utf-8", newline="") as f:
        f.write(HEADER)
        f.write("class\tsize\tb_C0\tb_C8\tb_D0\tstride_C8\tstride_D0\teven\tctor_body\n")
        for name, size, b0, b8, bd, h in rows:
            f.write("%s\t0x%X\t%08X\t%08X\t%08X\t0x%X\t0x%X\t%s\t%08X\n"
                    % (name, size, b0, b8, bd, b8 - b0, bd - b8,
                       "yes" if (b8 - b0) == (bd - b8) else "NO", h))
    print("wrote %s" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
