"""gen_entry_only_families.py - what the 4,832 undeclared entry-only mentions are made of.

`check_dispositions` reports the number and attributes it honestly:

    of the DOCUMENTED set, ENTRY-ONLY         :   8545
        of those, ALREADY declared B/C      :   3713   <- counted as explained
        genuinely undeclared entry-only     :   4832

**4,832 is the largest single undeclared population touching `engine_explained`**, which carries
0.55 of the completion weight - and nobody has published what it is MADE OF. A count routes
nothing. This groups it by `GFZ.V121.CodeDomain` family so a class declaration has somewhere to
start, and reproduces the checker's figure exactly as its own control.

THE SHAPE IS FLAT, AND THAT IS THE FINDING. There is no dominant family to declare: the largest
tagged group is 246. What there is instead is **1,433 functions - 29.7 % - with NO CodeDomain tag
at all**, entry-mentioned by a documented page and classified by nothing. That is the intersection
of two debts and it is the biggest single row.

A TAG IS NOT A SUBJECT, and a declaration built on one would be weak. Most of these families are
SHAPE taxonomy - `NativeRoutine.AcyclicDirectCall.Bounded.Conditional`, `NativeInline.NoCall.*` -
which describe control-flow form, not what the code is for. `check_dispositions` refuses a letter
"without a note - the bar is a falsifiable claim, not a label", and "these 246 functions all have
one bounded conditional call" is a label. The subject-shaped families here are the small ones:
`Phyre.Middleware.NativeQualified` (186), `Phyre.Reflection` (121), `Boundary.Audio` (54).

**Nothing is declared by this file.** It reports a population so that someone who can make a
falsifiable class claim knows where the mass is.
"""
import argparse
import collections
import io
import os
import re
import sys

KIT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(KIT))))
DB = os.path.join(REPO, "Database", "FFXII TZA")
FUNCS = os.path.join(REPO, "Database", "Tools", "work", "graph", "functions.tsv")
DOMAIN = re.compile(r"GFZ\.V121\.CodeDomain\.([A-Za-z0-9.]+)")
HEX8 = re.compile(r"^[0-9A-Fa-f]{8}$")
EXPECTED = 4832          # what check_dispositions reports; this file must reproduce it


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DB)
    a = ap.parse_args()
    sys.path.insert(0, KIT)
    try:
        import check_dispositions as cd
    except ImportError:
        print("CANNOT RUN: check_dispositions is not importable")
        return 2
    sizes = cd.load_functions()
    _a_set, entry_only, _ai, _da = cd.measure_a(a.db, sizes)
    declared, families = set(), 0
    for doc, parts in cd.parse_families(a.db):
        if len(parts) < 5:
            continue
        try:
            ms = cd.read_members(doc, parts[2])
        except (IOError, OSError, ValueError):
            continue
        if ms:
            families += 1
            declared |= set(ms)
    und = entry_only - declared

    # CONTROL. This file reconstructs a population check_dispositions already counts, so the two
    # must agree to the digit. A silent divergence would mean the grouping below describes some
    # other set than the one the gate reports, which is worse than not grouping it at all.
    print("UNDECLARED ENTRY-ONLY MENTIONS, BY FAMILY\n")
    print("  families read               : %d  (%d declared members)" % (families, len(declared)))
    print("  entry-only (documented)     : %d" % len(entry_only))
    print("  UNDECLARED entry-only       : %d" % len(und))
    if len(und) != EXPECTED:
        print("\n  CONTROL FAILED: check_dispositions reports %d and this reconstruction gives %d."
              % (EXPECTED, len(und)))
        print("  The grouping below would describe a different population; refusing to write it.")
        return 2
    print("  control passed: reproduces check_dispositions' figure exactly.")

    tag = {}
    if os.path.isfile(FUNCS):
        fh = io.open(FUNCS, encoding="utf-8", errors="replace")
        head = fh.readline().rstrip("\n").split("\t")
        ti = head.index("tags") if "tags" in head else None
        for line in fh:
            p = line.rstrip("\n").split("\t")
            if len(p) > 2 and HEX8.match(p[0]):
                t = p[ti] if ti is not None and len(p) > ti else ""
                m = DOMAIN.search(t)
                tag[int(p[0], 16)] = m.group(1) if m else "(no CodeDomain)"
    by = collections.Counter(tag.get(f, "(not in the function list)") for f in und)
    out = [
        "# The undeclared entry-only mentions, grouped by CodeDomain family.",
        "#",
        "# Generated by gen_entry_only_families.py, which reconstructs the population",
        "# check_dispositions counts and REFUSES TO WRITE unless the two figures match exactly.",
        "#",
        "# An entry-only mention is a documented page naming a function's ENTRY and never an",
        "# address inside its body. check_dispositions calls it a mention rather than an",
        "# explanation, and says of its own A figure that interior citation is a PROXY.",
        "#",
        "# A TAG IS NOT A SUBJECT. Most families here are SHAPE taxonomy - control-flow form, not",
        "# what the code is for - and a class declaration built on one would be a label, which",
        "# check_dispositions refuses. The subject-shaped families are the small ones.",
        "#",
        "# family\tfunctions",
    ]
    for k, v in by.most_common():
        out.append("%s\t%d" % (k, v))
    dest = os.path.join(a.db, "_index", "candidates", "entry-only-undeclared-families.tsv")
    io.open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

    print("\n  distinct families : %d" % len(by))
    notag = by.get("(no CodeDomain)", 0)
    print("  NO CodeDomain tag at all : %d  (%.1f%%)  <- the largest single row, and it is the"
          % (notag, 100.0 * notag / len(und)))
    print("                                          intersection of two debts")
    print("\n  largest tagged families:")
    for k, v in by.most_common(10):
        if k == "(no CodeDomain)":
            continue
        print("    %-58s %5d" % (k[:58], v))
    print("\n  THE SHAPE IS FLAT: the largest tagged family is %d, so there is no dominant class"
          % max(v for k, v in by.items() if k != "(no CodeDomain)"))
    print("  to declare. Nothing is declared by this file; it says where the mass is.")
    print("\n  wrote %s" % os.path.relpath(dest, REPO).replace(os.sep, "/"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
