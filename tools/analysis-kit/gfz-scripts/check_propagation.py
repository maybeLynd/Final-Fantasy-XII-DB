#!/usr/bin/env python3
"""check_propagation.py - FINAL-AUDIT-PROTOCOL pass 24, which had no tool.

Pass 24: *"for every correction ever made, verify every downstream citer was reopened"*, failing if
**any document still rests on an overturned claim**. Until now that was a read-every-line pass over
the whole corpus against a correction history nobody had collected.

It does not have to be. The board already keeps a structured, machine-readable correction registry:
every `kind: contradiction` task carries `original_claim` - the sentence that was overturned - and
`affected_documents` - where the correction was applied. 119 of them, every one with both fields.
This sweeps the first against the corpus and subtracts the second.

What it looks for
-----------------
The QUOTED SPANS inside `original_claim`. When a contradiction is filed properly it quotes the exact
retracted sentence, and a quoted sentence surviving verbatim in a document that the correction never
touched is the precise shape of a propagation failure. Bare addresses and offsets are deliberately
NOT used: `004B1190` appearing elsewhere is not a stale claim, it is an address that still exists,
and searching for those would bury the real finding under thousands of legitimate citations.

Three verdicts, because a hit is not automatically a defect
-----------------------------------------------------------
    EXPECTED     the hit is inside a document `affected_documents` names - the correction lives there
    QUOTED       the hit sits near a retraction marker - a page quoting what it is retracting
    SURVIVOR     everything else: a document repeating an overturned sentence, untouched  <- the pass

SURVIVOR is the only number that means anything, and it is still a TRIAGE result: a human reads each
one. This tool finds candidates; it does not decide.
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dispositions as DISP  # noqa: E402

MIN_SPAN = 24          # below this, quoted fragments are too generic to mean anything

# The single-quote arm needs guarding: an apostrophe inside a POSSESSIVE or a contraction is not an
# opening delimiter. Without the guards below, `the record's fifth dword is that kind' of thing`
# yields the span "s fifth dword is that kind", which begins mid-word and matches half the corpus.
# So an opening ' must not follow a word character, and a closing ' must not precede one.
QUOTED = re.compile(
    r"(?<![A-Za-z0-9])'([^']{%d,200})'(?![A-Za-z0-9])"
    r"|\"([^\"]{%d,200})\""
    r"|`([^`]{%d,200})`" % (MIN_SPAN, MIN_SPAN, MIN_SPAN))
# A document named in `affected_documents` is named in EITHER spelling, and until 2026-09-18 only
# one of them was read. 90 of the 249 contradiction tasks on the board write their affected set
# DB-relative - "_index/OPEN-QUESTIONS.md", "16-UI/Battle-Hud/the-battle-hud-layout-readers.md" -
# and for those tasks this regex returned nothing at all. A correction that names five documents
# was treated as naming none, so EXPECTED (a hit inside a document the correction points at) could
# not fire, and the correction's own worked examples were reported as pages repeating what they
# correct. Three survivors and six QUOTED classifications were of exactly that shape.
#
# The DB-relative alternative is anchored on a top-level corpus directory rather than on "any word",
# so a sentence cannot match: a two-digit section, `_index/` or `_experiments/`, not preceded by a
# word character. CONTROL, run before this was adopted: 186 distinct paths extracted across the
# whole board, 181 resolving to a real file; the five that do not are hand-written stale page names
# (e.g. 16-UI/dynamic-geometry-instances/dyngeo-instance-family.md), not regex noise.
PATHS = re.compile(r"(?:Database/FFXII TZA/|(?<![\w/])(?=(?:\d\d-|_index/|_experiments/)))"
                   r"[^\s;,()]+?\.(?:md|tsv)")
MARKER = re.compile(
    r"RETRACT|SUPERSED|CORRECT|WITHDRAWN|OVERTURN|was wrong|no longer|previously|"
    r"~~|formerly|earlier reading|struck", re.I)
SKIP_DIRS = {".git", "_templates", "_inbox"}
WS = re.compile(r"\s+")



# A bare link bullet in a file that declares itself GENERATED: `- [label](target)` and nothing
# else. The label is a heading's NAME, so a contradiction matching it has matched a reference to
# the rule rather than a repetition of the claim. Narrow on purpose - it does not exempt the file,
# only lines that carry no assertion of their own.
_GEN_HEADER = re.compile(r"Generated by `?\w+\.py|Do not edit; regenerate", re.I)
_LINK_ONLY = re.compile(r"^\s*[-*]\s*\[[^\]]*\]\([^)]*\)\s*$")
_gen_cache = {}


def _is_generated_index_link(path, line_no):
    try:
        if path not in _gen_cache:
            text = open(path, encoding="utf-8", errors="replace").read()
            head = "\n".join(text.split("\n")[:12])
            _gen_cache[path] = (bool(_GEN_HEADER.search(head)), text.split("\n"))
        generated, lines = _gen_cache[path]
        if not generated or not (1 <= line_no <= len(lines)):
            return False
        return bool(_LINK_ONLY.match(lines[line_no - 1]))
    except (IOError, OSError):
        return False

def norm(s):
    return WS.sub(" ", s).strip()


def spans_from(task):
    """The quoted, overturned sentences inside one contradiction's original_claim."""
    out = []
    for m in QUOTED.finditer(task.get("original_claim") or ""):
        for g in m.groups():
            if g and len(norm(g)) >= MIN_SPAN:
                out.append(norm(g))
    return out


def corpus(db):
    for root, dirs, names in os.walk(db):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for n in sorted(names):
            if n.endswith((".md", ".tsv")):
                p = os.path.join(root, n)
                try:
                    yield p, open(p, encoding="utf-8").read()
                except (OSError, UnicodeDecodeError):
                    continue


def locate(text, span, window=3):
    """Line number of the first line containing the span, plus its NEIGHBOURHOOD.

    The neighbourhood is what gets tested for a retraction marker, and it has to be: a page that
    quotes a claim while retracting it usually puts the marker in the surrounding sentence, not on
    the quoted line. The first version of this checked only the hit line and duly reported
    `world-loot-pickups...md` as a survivor for repeating "a tuning slot currently set to unity" -
    when the sentence one line above reads "I had spent the morning publishing - and then RETRACTING
    - the claim that ...". The page was recording the correction, which is the opposite of resting
    on it.
    """
    lines = text.splitlines()
    head = span[:40]
    for i, line in enumerate(lines, 1):
        if head in norm(line):
            lo, hi = max(0, i - 1 - window), min(len(lines), i + window)
            return i, norm(" ".join(lines[lo:hi]))

    # The span straddles a line break, so no single line holds its head. Returning an empty
    # neighbourhood here meant the marker test never ran and the hit fell through to SURVIVOR -
    # which is how a wrapped quotation inside a retraction was reported as a stale claim. Fall back
    # to a character window in the normalised document.
    flat = norm(text)
    at = flat.find(span)
    if at < 0:
        return None, ""
    return None, flat[max(0, at - 320):at + len(span) + 320]


DATED_HEAD = re.compile(r"^#{1,4}\s.*20\d\d-\d\d-\d\d")


def dated_scope(text):
    """-> set of 1-based line numbers that sit under a dated heading.

    Sticky down the heading tree: a dated entry contains undated sub-headings ("### What was
    deliberately not claimed"), and resetting on every heading would turn the flag off immediately.
    A section stays dated until a heading at the SAME OR SHALLOWER level says otherwise.

    ONE (flag, level) PAIR IS NOT ENOUGH, and it was what this did until 2026-09-18. A dated
    SUBSECTION inside a dated section overwrote the enclosing section's level; the next undated
    sibling at that level then satisfied `lv <= level` and cleared the flag outright, throwing away
    an outer dated scope that was still open. The rule above was the intent all along - the code
    simply could not express it with one number.

    The case that exposed it: `## Addendum 2026-09-15bk` (dated, level 2) containing `### Kind (d),
    added 2026-09-18` (dated, level 3) followed by `### What it is NOT for` (undated, level 3).
    That last heading closed level 3 AND level 2, and the addendum's remaining subsections stopped
    being dated sixteen lines before the one the pass-24 sweep then reported.

    A stack says it directly: a heading at level lv closes every dated section at lv or deeper, and
    nothing else.
    """
    out, stack = set(), []
    for i, line in enumerate(text.split("\n"), 1):
        m = re.match(r"^(#{1,6})\s", line)
        if m:
            lv = len(m.group(1))
            while stack and stack[-1] >= lv:
                stack.pop()
            if DATED_HEAD.match(line):
                stack.append(lv)
        if stack:
            out.add(i)
    return out


def sweep(db, board):
    tasks = [t for t in board["tasks"] if t.get("kind") == "contradiction"]
    docs = list(corpus(db))
    normed = [(p, norm(t)) for p, t in docs]
    raw = dict(docs)

    counts = {"EXPECTED": 0, "QUOTED": 0, "DATED": 0, "SURVIVOR": 0}
    dated_lines = {p: dated_scope(raw[p]) for p, _ in normed}
    survivors = []
    used = 0
    for t in tasks:
        spans = spans_from(t)
        if not spans:
            continue
        used += 1
        affected = set(PATHS.findall(t.get("affected_documents") or ""))
        affected = {a.replace("/", os.sep) for a in affected}
        for span in spans:
            for p, body in normed:
                if span not in body:
                    continue
                rel = os.path.relpath(p, db)
                if any(rel.endswith(a.split("FFXII TZA" + os.sep)[-1]) for a in affected):
                    counts["EXPECTED"] += 1
                    continue
                line_no, line = locate(raw[p], span)
                if MARKER.search(line):
                    counts["QUOTED"] += 1
                    continue
                # A SECTION UNDER A DATED HEADING IS A RECORD OF THAT DATE, not a live claim.
                # Both survivors this test had on 2026-09-14 were of exactly this shape: the same
                # quoted §13 text, once in `AUDIT-LOG.md` under "## 2026-09-08 - a checker validated
                # on the failure it was built for", and once in `COVERAGE.md` under "## 2026-09-08 -
                # the fourth contract...". Neither is a page repeating an overturned sentence - each
                # is a page QUOTING what the contract said on the day it was examined, which is the
                # log and the coverage page doing their job.
                #
                # This is the same structural rule `check_index_figures` and `check_dimension_figures`
                # use, applied here rather than kept as two named waivers: a rule generalises to the
                # next dated entry, a waiver list does not.
                if line_no is not None and line_no in dated_lines.get(p, ()):
                    counts["DATED"] += 1
                    continue
                # A TABLE-OF-CONTENTS ENTRY CARRIES A RULE'S NAME, NOT ITS CLAIM. `RULES.md:245`
                # was reported for the line `- [What a row must carry before it may take it](
                # EVIDENCE-STANDARD.md#...)` - a generated index linking the heading of the very
                # rule the contradiction invokes. The file's own header settles it: "Generated by
                # gen_rules_index.py. Do not edit; regenerate. ... It is an index, never a copy -
                # the source file is always authoritative." A generated index cannot hold a stale
                # claim independently of its source; when the source moves, regenerating carries
                # it, which is what happened on 2026-09-15 (d69401fa).
                #
                # THIS DOES NOT REOPEN SWE2-AUDIT-SPEC'S RULING that _index/ABSENCE-CLAIM-AUDIT.tsv
                # belongs in the affected set as "a derived index carrying the overturned
                # sentence". That one carries the SENTENCE. This test fires only where the matched
                # span is the label of a bare link bullet - the whole line is `- [text](target)` -
                # in a file that declares itself generated. A derived index that repeats the claim
                # still counts, exactly as AUDIT-SPEC ruled. Use versus mention, the same
                # distinction as the truncated-name and scoping-idiom rulings of the same day.
                # OPUS, 2026-09-15, answering FABLE's "does a contradiction quoting a rule it
                # invokes count as a survivor".
                if line_no is not None and _is_generated_index_link(p, line_no):
                    counts["QUOTED"] += 1
                    continue
                counts["SURVIVOR"] += 1
                survivors.append((t["id"], rel, line_no, span))
    return len(tasks), used, counts, survivors


def self_test():
    """A checker that cannot demonstrate a known positive is not evidence of anything."""
    board = {"tasks": [{
        "id": "TEST-CONTRA", "kind": "contradiction",
        "original_claim": "the page said 'the widget pool holds exactly 112 fixed slots' and it does not",
        "affected_documents": "Database/FFXII TZA/16-UI/fixed.md"}]}
    import tempfile
    d = tempfile.mkdtemp()
    ui = os.path.join(d, "16-UI")
    os.makedirs(ui)
    # the corrected page - names the claim while retracting it
    open(os.path.join(ui, "fixed.md"), "w", encoding="utf-8").write(
        "RETRACTED: the widget pool holds exactly 112 fixed slots\n")
    # an untouched downstream page still asserting it  <- must be found
    open(os.path.join(ui, "stale.md"), "w", encoding="utf-8").write(
        "As established, the widget pool holds exactly 112 fixed slots.\n")
    # a page that quotes it while marking it superseded  <- must NOT be found
    open(os.path.join(ui, "quoting.md"), "w", encoding="utf-8").write(
        "SUPERSEDED claim: the widget pool holds exactly 112 fixed slots\n")
    _n, used, counts, surv = sweep(d, board)
    ok = (used == 1 and counts["SURVIVOR"] == 1
          and surv and surv[0][1].endswith("stale.md"))
    print("self-test: %s  (used %d, survivors %d: %s)"
          % ("PASS" if ok else "FAIL", used, counts["SURVIVOR"],
             [s[1] for s in surv]))

    # ---- KNOWN POSITIVE FOR DEFECT A: a dated section survives its dated subsection ------------
    # `## Addendum 2026-09-15bk` contains `### Kind (d), added 2026-09-18`, then an UNDATED sibling
    # at the same level. Before 2026-09-18 that sibling closed the addendum too, and every later
    # subsection of a dated section was reported as a live claim. Both sub-headings are needed:
    # with only the undated one the old code was already correct, which is why nothing caught this.
    b2 = {"tasks": [{"id": "TEST-DATED", "kind": "contradiction",
                     "original_claim": "the register said 'five rows predate the bar they cite'",
                     "affected_documents": ""}]}
    d2 = tempfile.mkdtemp()
    os.makedirs(os.path.join(d2, "_index"))
    open(os.path.join(d2, "_index", "STANDARD.md"), "w", encoding="utf-8").write(
        "# Standard\n\n## Addendum 2026-09-15bk - the bar\n\n### Kind (d), added 2026-09-18\n\n"
        "text\n\n### What it is NOT for\n\nmore text\n\n### The bar itself\n\n"
        "five rows predate the bar they cite\n")
    _n2, _u2, c2, s2 = sweep(d2, b2)
    ok2 = c2["SURVIVOR"] == 0 and c2["DATED"] == 1
    print("  A: a dated section survives its dated subsection   %s  (DATED %d, SURVIVOR %d)"
          % ("PASS" if ok2 else "FAIL", c2["DATED"], c2["SURVIVOR"]))

    # ---- KNOWN POSITIVE FOR DEFECT B: a DB-RELATIVE affected document is read ------------------
    # Same fixture as the main test, with the affected document written the way 90 of the board's
    # 249 contradictions write it. Before 2026-09-18 PATHS returned nothing for this spelling, the
    # correction was treated as naming no documents, and its own corrected page became a survivor.
    b3 = {"tasks": [{"id": "TEST-RELPATH", "kind": "contradiction",
                     "original_claim": "the page said 'the widget pool holds exactly 112 fixed slots'",
                     "affected_documents": "16-UI/fixed.md and _index/OPEN-QUESTIONS.md"}]}
    d3 = tempfile.mkdtemp()
    os.makedirs(os.path.join(d3, "16-UI"))
    open(os.path.join(d3, "16-UI", "fixed.md"), "w", encoding="utf-8").write(
        "Restated on the page the board points at: the widget pool holds exactly 112 fixed "
        "slots.\n")
    _n3, _u3, c3, s3 = sweep(d3, b3)
    ok3 = c3["EXPECTED"] == 1 and c3["SURVIVOR"] == 0
    print("  B: a DB-relative affected document is read         %s  (EXPECTED %d, SURVIVOR %d)"
          % ("PASS" if ok3 else "FAIL", c3["EXPECTED"], c3["SURVIVOR"]))

    return 0 if (ok and ok2 and ok3) else 1


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--db")
    ap.add_argument("--board")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    if not (a.db and a.board):
        return ap.error("--db and --board, or --self-test")

    board = json.load(open(a.board, encoding="utf-8"))
    total, used, counts, survivors = sweep(a.db, board)

    # THE REGISTRY THIS PASS ASKED FOR, APPLIED TO THIS PASS. Subject is
    # contradiction-id::document - the pair a reviewer actually judges - and the evidence
    # is the matched span, so rewording the sentence (which is what a repair does) lapses
    # the disposition and the survivor returns.
    reg = DISP.Registry(a.db, "check_propagation.py")
    live = []
    for cid, rel, line, span in survivors:
        subject = "%s::%s" % (cid, rel.replace(os.sep, "/"))
        if reg.suppressed(subject, span):
            continue
        live.append((cid, rel, line, span))
    dispositioned = len(survivors) - len(live)
    survivors = live
    counts["SURVIVOR"] = len(survivors)
    print("FINAL-AUDIT-PROTOCOL pass 24 - propagation sweep (DIAGNOSTIC, not a gate pass)")
    print("  %d contradiction tasks on the board; %d carry a quoted span of >=%d chars"
          % (total, used, MIN_SPAN))
    print("    EXPECTED  %4d   hit inside a document the correction names" % counts["EXPECTED"])
    print("    QUOTED    %4d   hit beside a retraction marker - a page quoting what it retracts"
          % counts["QUOTED"])
    print("    DATED     %4d   hit under a dated heading - a log or a page recording what it"
          % counts["DATED"])
    print("                      found on that date, not a live claim. REPORTED, never hidden:")
    print("                      absorbing preserved history silently is the failure the")
    print("                      evidence standard forbids, and it is what a bare 0 would do.")
    print("    SURVIVOR  %4d   <- the only number that matters (%d suppressed by a"
          "\n                      reviewed disposition)"
          % (counts["SURVIVOR"], dispositioned))
    # A LAPSE MUST PRINT WHETHER OR NOT --list IS GIVEN. Silence about a disposition that
    # no longer matches its evidence is exactly the blindfold the registry prevents.
    for _line in reg.report():
        print(_line)
    if a.list:
        for cid, rel, line, span in survivors:
            print("\n  %s\n    %s:%s\n    %r" % (cid, rel, line, span[:150]))
    if not counts["SURVIVOR"]:
        print("\n  No document repeats an overturned sentence outside its own correction.")
        print("  The self-test demonstrates a known positive, so that is a real negative.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
