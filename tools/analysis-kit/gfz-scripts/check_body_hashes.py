"""check_body_hashes.py - FINAL-AUDIT pass 3, which had no instrument.

Pass 3 is *"recompute every cited hash, in the correct convention; fails on any mismatch, or a prose
hash used where the gate wants address-salted"*. Nothing in the kit computed either convention, so
the pass could only ever be asserted. This computes both, from the authority image, and compares
them to what the corpus actually cites.

THE TWO CONVENTIONS, and where each is defined:

  plain          `sha256(body bytes)`. What ASTRA's probes publish - arena_alloc_probe.py,
                 arena_init_probe.py, cap_policy_probe.py, efx_rebase_probe.py all write
                 `body_sha256={hex(a): hashlib.sha256(b).hexdigest() ...}`.

  address-salted per body range in iteration order, `BE64(range.min) || BE64(range.max) || bytes`.
                 Transcribed from `Database/Tools/ghidra/scripts/EnrichCurrentBodyManifest.java:5`,
                 the manifest the GZF apply gate compares against. Ghidra's `getMaxAddress()` is the
                 LAST byte of the range, so it is `min + length - 1`.

Both reproduce byte-exactly, and the corpus distinguishes them correctly. The same 289-byte body at
`00313A00` is cited twice on one page: as `c076cfea...9d246`, labelled *"plain-body"*, and as
`0966b7b4...a16071`, labelled *"gate hash"*. AUDIT-LOG:160 records why that matters - the enricher
produced the salted pair where *"the handoff prose quotes"* the plain one, and *"a hand-built
manifest would have aborted"*.

THE POPULATION IS NOT WHAT A 64-HEX SWEEP FINDS. A blanket `[0-9a-f]{64}` match returns 1,136
tokens of which 995 are nine provenance stamps, and only eight citations whose own words say "body
hash". **The corpus cites hashes TRUNCATED**, head-ellipsis-tail, inside the evidence cell of a
claim table, and a 64-hex regex matches none of them:

    | Recipe domain 0..108 | complete body of `00385F60` (2,302 B, `f887bb1f...8142`) | 1 |

The head is always 8 characters; the tail is 4, 5, 6 or 8 and is the LAST characters of the hash.
That convention is not assumed here, it is measured: the 58 truncated provenance stamps reproduce
it 58 times out of 58.

HEAD AND TAIL ARE REPORTED SEPARATELY, because they fail separately and mean different things. Eight
hex characters is 32 bits, so a head that reproduces at the stated length means the citation names
the right body, at the right size, in the right convention. A wrong tail on such a row is four to
six mis-transcribed characters - NOT a wrong body and NOT the wrong convention, which is the failure
pass 3 was written to catch. Saying "hash mismatch" for both would bury the distinction.

WHAT IT CANNOT CHECK, stated rather than implied. `body_bytes` in the function census is
`getNumAddresses()`, the address count across ALL ranges of a body. A non-contiguous body laid down
as one run from its entry is the wrong byte string, so such a row cannot be recomputed here; it is
reported as UNREPRODUCED and never as a wrong hash. Citations that name no address of their own - a
jump table, a 43-byte PSM table hung off another function's row - have nothing to recompute against
and are reported as such, which is a weakness in the citation rather than a defect in the value.
"""
import argparse, collections, hashlib, io, os, re, struct, sys

DB_DEFAULT = "Database/FFXII TZA"
EXE_DEFAULT = os.path.join("Database", "Tools", "work", "exe", "FFXII_TZA.exe")
EXE_SHA = "73461d0896204b1c259c52f61aef4efbc95a2ffc388cadb36493d5d1d89721f8"
FUNCS_DEFAULT = os.path.join("Database", "Tools", "work", "graph", "functions.tsv")

# CASE-INSENSITIVE, because a wrong tail hid behind capitals. Four sibling pages cite the authority
# EXE as `73461D08…97F8` and `97f8` does not occur in that hash at all - the same mis-transcription
# class this checker was written for, propagated by copying, and invisible while the pattern
# demanded lowercase.
#
# THE COST OF WIDENING IS ADDRESS RANGES. `01F2CE88…01F2CED0` in AUDIT-LOG is a RANGE, not a
# truncated hash, and it has exactly the same shape once case stops distinguishing them. A range is
# recognised by its tail: eight hex digits that parse as an address inside the image, with the
# head doing likewise. Those are skipped rather than reported as unreproducible hashes.
TRUNC = re.compile(r"(?<![0-9a-fA-F])([0-9a-fA-F]{8})\s*(?:…|\.\.\.)\s*([0-9a-fA-F]{3,8})"
                   r"(?![0-9a-fA-F])")
FULL = re.compile(r"(?<![0-9a-fA-F])([0-9a-f]{64})(?![0-9a-fA-F])")
ADDR = re.compile(r"(?<![0-9A-Fa-f])(0[0-9A-Fa-f]{7})(?![0-9A-Fa-f])")
BYTES = re.compile(r"\(?\s*([\d,]+)\s*(?:B|bytes)\b")

TSV_HEADER = [
    "# Every truncated hash citation in the corpus, with what it was checked against.",
    "# Generated by check_body_hashes.py --tsv; regenerate rather than editing by hand.",
    "#",
    "#   plain-ok            head and tail reproduce sha256(body) for the bytes at the cited",
    "#                       address and length",
    "#   salted-ok           head and tail reproduce the EnrichCurrentBodyManifest salt,",
    "#                       BE64(min)||BE64(max)||bytes - the value the GZF apply gate compares",
    "#   provenance-ok       a truncated image/snapshot stamp that reproduces the full value",
    "#   corpus-consistent   no body to recompute, but the corpus records the full value elsewhere",
    "#                       and the truncation matches it. Internal consistency, not the image.",
    "#   *-TAIL-WRONG        the 8-character head reproduces and the trailing characters do not.",
    "#                       The body, length and convention are right; the tail is mis-transcribed.",
    "#   unreproduced        nothing to recompute against - a citation naming no address of its own,",
    "#                       or a body that is not contiguous. NOT a wrong hash.",
    "#",
    "# document\tline\tcited_head\tcited_tail\tverdict\tchecked_against\tcorrect_full_hash",
]


class Image(object):
    """Minimal PE map: virtual address -> file bytes."""

    def __init__(self, path):
        self.data = open(path, "rb").read()
        pe = struct.unpack_from("<I", self.data, 0x3C)[0]
        if self.data[pe:pe + 4] != b"PE\0\0":
            raise ValueError("not a PE image: %s" % path)
        nsec = struct.unpack_from("<H", self.data, pe + 6)[0]
        optsz = struct.unpack_from("<H", self.data, pe + 20)[0]
        magic = struct.unpack_from("<H", self.data, pe + 24)[0]
        self.base = (struct.unpack_from("<Q", self.data, pe + 48)[0] if magic == 0x20B
                     else struct.unpack_from("<I", self.data, pe + 52)[0])
        self.secs = []
        off = pe + 24 + optsz
        for i in range(nsec):
            n = off + 40 * i
            vsz = struct.unpack_from("<I", self.data, n + 8)[0]
            va = struct.unpack_from("<I", self.data, n + 12)[0]
            rawsz, rawoff = struct.unpack_from("<II", self.data, n + 16)
            self.secs.append((va, vsz, rawsz, rawoff))

    def read(self, va, n):
        rva = va - self.base
        for secva, vsz, rawsz, rawoff in self.secs:
            if secva <= rva < secva + max(vsz, rawsz):
                d = rva - secva
                if d + n > rawsz:
                    return None
                return self.data[rawoff + d:rawoff + d + n]
        return None


def plain(body):
    return hashlib.sha256(body).hexdigest()


def salted(minva, body):
    """EnrichCurrentBodyManifest.java:5, for one contiguous range."""
    md = hashlib.sha256()
    md.update(struct.pack(">Q", minva))
    md.update(struct.pack(">Q", minva + len(body) - 1))
    md.update(body)
    return md.hexdigest()


def docs(db):
    for root, dirs, files in os.walk(db):
        # `_inbox/` is agent correspondence, not publication, and `check_doc_self.py` already
        # excludes it for the same reason. A checkpoint that QUOTES a citation as an example -
        # "the corpus cites hashes truncated, `f887bb1f...8142`" - is discussing a hash, not
        # claiming one, and has no address to recompute against because it should not have one.
        # `_index/` stays in: AUDIT-LOG's provenance citations are real claims and do verify.
        dirs[:] = [d for d in dirs if d not in (".git", "_inbox")]
        for f in sorted(files):
            if f.endswith(".md"):
                yield os.path.join(root, f)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DB_DEFAULT)
    ap.add_argument("--exe", default=EXE_DEFAULT)
    ap.add_argument("--functions", default=FUNCS_DEFAULT)
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--tsv", help="also write every citation and its verdict to this file")
    a = ap.parse_args(argv)

    if not os.path.isfile(a.exe):
        print("check_body_hashes: no image at %s" % a.exe)
        print("  ABSTAINING - pass 3 cannot be run without the authority binary, and a checker that")
        print("  returns green because it never reached the rows costs the audit.")
        return 3
    got = hashlib.sha256(open(a.exe, "rb").read()).hexdigest()
    if got != EXE_SHA:
        print("check_body_hashes: %s is NOT the authority binary" % a.exe)
        print("  expected %s\n  got      %s" % (EXE_SHA, got))
        return 3
    img = Image(a.exe)

    sizes = {}
    if os.path.isfile(a.functions):
        with io.open(a.functions, encoding="utf-8", errors="replace") as fh:
            next(fh)
            for line in fh:
                c = line.rstrip("\n").split("\t")
                if len(c) > 2 and c[2].isdigit():
                    sizes[int(c[0], 16)] = int(c[2])

    texts, full_counts = {}, collections.Counter()
    for p in docs(a.db):
        texts[p] = io.open(p, encoding="utf-8", errors="replace").read()
        for m in FULL.finditer(texts[p]):
            full_counts[m.group(1)] += 1
    # a value written out in full ten or more times is a provenance stamp, not a body
    stamps = [h for h, c in full_counts.items() if c >= 10]

    v, tl, bad, unresolved = collections.Counter(), collections.Counter(), [], []
    allrows = []
    for p in sorted(texts):
        rel = os.path.relpath(p, a.db).replace(os.sep, "/")
        lines = texts[p].split("\n")
        # A SALTED citation usually names no address on its own line. The gate hash reads "Fenced
        # against the live parent (body 289 B, gate hash `0966b7b4...a16071`)" in a Status paragraph
        # whose subject, `00313A00`, was last written 23 lines earlier. A fixed few-line window
        # misses it, so the fallback is EVERY address in the document, tried nearest-first.
        #
        # That is safe rather than sloppy, and the reason is arithmetic: a candidate only verifies
        # if the 8-character head reproduces, which is 32 bits. Trying a hundred wrong addresses
        # under two conventions gives a false-positive probability around 2e-8. Proximity decides
        # the ORDER, the hash decides the ANSWER.
        docaddrs = []
        for ln_no, ln in enumerate(lines, 1):
            for s in ADDR.findall(ln):
                docaddrs.append((ln_no, s))
        for n, line in enumerate(lines, 1):
            nearby = [s for _d, s in sorted(((abs(ln_no - n), s) for ln_no, s in docaddrs),
                                            key=lambda t: t[0])]
            for m in TRUNC.finditer(line):
                head, tail = m.group(1).lower(), m.group(2).lower()
                # KNOWN HASH FIRST, RANGE TESTS SECOND, and the order is not cosmetic. The range
                # tests below are structural guesses, and `73461d08...21f8` - the authority EXE
                # stamp - satisfies the abbreviated-range test by pure coincidence of its digits
                # (`7346`+`21f8` sits 0x4F0 above `73461d08`). Running them first quietly
                # reclassified two real provenance citations as address ranges and dropped
                # provenance-ok from 34 to 32. A value the corpus records in full is a hash; no
                # structural guess gets to overrule that.
                if any(h.startswith(head) for h in stamps):
                    pass
                else:
                    # AN ADDRESS RANGE, NOT A TRUNCATED HASH. Tested structurally rather than by
                    # reading the image: `022D9198...022D9318` and `022C8060...022C8078` live in
                    # sections with no raw bytes on disk, so an image-read test misses exactly the
                    # ranges it was meant to catch. A range is two 8-digit values, ascending, a
                    # short distance apart; a hash's tail bears no such relation to its head.
                    #
                    # THE ABBREVIATED RANGE is the same thing with the end's common prefix dropped:
                    # `02CB8100 ... 812C   ids 78..89` means 02CB8100 to 02CB812C. Splice the tail
                    # onto the head's prefix and ask the same question.
                    rng = False
                    if len(tail) == 8:
                        lo, hi = int(head, 16), int(tail, 16)
                        rng = 0 < hi - lo < 0x10000
                    elif 3 <= len(tail) <= 4:
                        lo = int(head, 16)
                        hi = int(head[:8 - len(tail)] + tail, 16)
                        rng = 0 < hi - lo < 0x1000
                    if rng:
                        v["address-range-not-a-hash"] += 1
                        continue
                tl[len(tail)] += 1
                stamp = [h for h in stamps if h.startswith(head)]
                if stamp:
                    if stamp[0].endswith(tail):
                        v["provenance-ok"] += 1
                        allrows.append((rel, n, head, tail, "provenance-ok", "stamp", stamp[0]))
                    else:
                        v["PROVENANCE-TAIL-WRONG"] += 1
                        allrows.append((rel, n, head, tail, "PROVENANCE-TAIL-WRONG", "stamp", stamp[0]))
                        bad.append((rel, n, head, tail, stamp[0], "stamp"))
                    continue
                # nearest address and byte count to the LEFT belong to this hash: one cell often
                # holds two citations
                before = line[:m.start()]
                # A HASH HEAD IS SHAPED EXACTLY LIKE AN ADDRESS: `0966b7b4` is eight hex digits
                # starting with a zero, so the head of the very citation being checked matches the
                # address pattern. Short-circuiting on "the line has an address" therefore picked
                # the hash itself and never fell back to the real address a few lines above. Build
                # the candidate list from all three sources in priority order, drop the head, and
                # let the 32-bit head comparison decide which one is right.
                addrs = (list(reversed(ADDR.findall(before)))
                         + ADDR.findall(line) + nearby)
                seen = set([head])
                addrs = [s for s in addrs
                         if not (s.lower() in seen or seen.add(s.lower()))]
                bs = list(reversed(BYTES.findall(before))) or BYTES.findall(line)
                stated = int(bs[0].replace(",", "")) if bs else None
                cands = []
                for s in addrs:
                    va = int(s, 16)
                    if va in sizes:
                        cands.append((va, sizes[va]))
                    if stated is not None and (va not in sizes or sizes[va] != stated):
                        cands.append((va, stated))
                best = None
                for va, ln in cands:
                    body = img.read(va, ln)
                    if body is None:
                        continue
                    for conv, h in (("plain", plain(body)), ("salted", salted(va, body))):
                        if h.startswith(head):
                            best = (va, conv, h, ln)
                            break
                    if best:
                        break
                if not best:
                    # LAST RESORT, and a weaker claim that is labelled as one. Some truncations
                    # cite a snapshot or residual list - `d2445517...e61a20` - that the corpus
                    # records in full elsewhere but fewer than ten times, so it is not in the stamp
                    # set and there is no body to recompute. Checking the truncation against the
                    # corpus's own full record is still a real check; it just verifies INTERNAL
                    # CONSISTENCY rather than the image, so it gets its own name and is never
                    # counted as a recomputation.
                    ref = [h for h in full_counts if h.startswith(head)]
                    if ref:
                        if ref[0].endswith(tail):
                            v["corpus-consistent"] += 1
                            allrows.append((rel, n, head, tail, "corpus-consistent", "corpus full value", ref[0]))
                        else:
                            v["CORPUS-TAIL-WRONG"] += 1
                            allrows.append((rel, n, head, tail, "CORPUS-TAIL-WRONG", "corpus full value", ref[0]))
                            bad.append((rel, n, head, tail, ref[0],
                                        "full value recorded elsewhere in the corpus"))
                        continue
                    v["unreproduced"] += 1
                    allrows.append((rel, n, head, tail, "unreproduced", "", ""))
                    unresolved.append((rel, n, head, tail))
                    continue
                va, conv, h, ln = best
                if h.endswith(tail):
                    v["%s-ok" % conv] += 1
                    allrows.append((rel, n, head, tail, "%s-ok" % conv, "%08X len %d" % (va, ln), h))
                else:
                    v["%s-TAIL-WRONG" % conv] += 1
                    allrows.append((rel, n, head, tail, "%s-TAIL-WRONG" % conv, "%08X len %d" % (va, ln), h))
                    bad.append((rel, n, head, tail, h, "%08X len %d" % (va, ln)))

    if a.tsv:
        with io.open(a.tsv, "w", encoding="utf-8", newline="\n") as fh:
            for ln in TSV_HEADER:
                fh.write(ln + "\n")
            for row in allrows:
                fh.write("\t".join(str(x) for x in row) + "\n")
        if not a.quiet:
            print("  wrote %s (%d rows)\n" % (a.tsv, len(allrows)))

    if not a.quiet:
        print("FINAL-AUDIT pass 3 - every cited hash recomputed, in both conventions\n")
        print("  image                : %s" % a.exe)
        print("  truncated citations  : %d" % sum(v.values()))
        for k in sorted(v):
            print("      %-24s %d" % (k, v[k]))
        print("  tail width as cited  : %s"
              % ", ".join("%d chars x%d" % (k, tl[k]) for k in sorted(tl)))
        print()
        if unresolved:
            print("  UNREPRODUCED - nothing to recompute against, NOT a wrong hash: %d"
                  % len(unresolved))
            print("      a body that is not contiguous, or a citation naming no address of its own")
            for rel, n, head, tail in unresolved[:10]:
                print("      %-58s line %-5d %s...%s" % (rel[:58], n, head, tail))
            print()
        if bad:
            print("  MISMATCHES - the head reproduces, the trailing characters do not\n")
            for rel, n, head, tail, h, where in bad:
                print("      %s:%d" % (rel, n))
                print("          cited   %s...%s   (%s)" % (head, tail, where))
                print("          correct %s" % h)
        else:
            print("  no mismatch: every citation that can be recomputed reproduces, head and tail.")

    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
