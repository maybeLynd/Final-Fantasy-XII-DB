def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DB)
    a = ap.parse_args()
    db = a.db
    hits = collections.defaultdict(list)
    gen_hits = collections.defaultdict(list)
    scanned = 0
    for root, dirs, files in os.walk(db):
        dirs[:] = [d for d in dirs if d != ".git"]
        for f in sorted(files):
            if not f.endswith(".md"):
                continue
            p = os.path.join(root, f)
            rel = os.path.relpath(p, db).replace(os.sep, "/")
            scanned += 1
            lines = io.open(p, encoding="utf-8", errors="replace").read().split("\n")
            generated = bool(GENERATED.search("\n".join(lines[:15])))
            for n, line in enumerate(lines, 1):
                m = ABSENCE.search(line)
                if not m:
                    continue
                for t in TYPES:
                    if t in line:
                        (gen_hits if generated else hits)[t].append(
                            (rel, n, m.group(0), " ".join(line.split())[:150],
                             DISP.digest(line)))

    # "SEVEN" WAS A LITERAL IN FOUR SENTENCES HERE and the set is eleven. Derived now, for the
    # same reason TYPES is: a count written by hand is a copy of a measurement and goes stale
    # silently. 2026-09-14 (OPUS).
    print("Absence claims about the %d types whose census cannot see their constructor\n"
          % len(TYPES))
    print("  documents scanned : %d" % scanned)
    print("  types checked     : %d  (derived from check_census_writers, not a copied list)\n"
          % len(TYPES))
    total = sum(len(v) for v in hits.values())
    inbox, cleared, routed, unread = 0, 0, 0, []
    for t in TYPES:
        rows = hits.get(t, [])
        print("  %-28s %d" % (t, len(rows)))
        for rel, n, phrase, line, dig in rows:
            key = (rel.replace("\\", "/"), dig)
            if INBOX.search(key[0]):
                inbox += 1
                verdict = "AGENT INBOX - a working note, not a publication"
            elif key in READ:
                # A ROUTED ROW IS READ BUT NOT CLEARED, and folding it into "cleared" would
                # report owed work as settled work. Its own bucket, so the count is honest.
                if READ[key].startswith("ROUTED"):
                    routed += 1
                else:
                    cleared += 1
                verdict = READ[key]
            else:
                unread.append((t, rel, n, phrase, line))
                verdict = "UNREAD"
            print("      %s:%d   (\"%s\")" % (rel, n, phrase))
            print("          %s" % line)
            print("          -> %s" % verdict[:150])
    print()
    print("  total absence claims naming one of the %d on the same line: %d" % (len(TYPES), total))
    print("    in an agent inbox, not a publication : %d" % inbox)
    print("    read by hand and cleared, with a reason : %d" % cleared)
    print("    read and ROUTED - owed, not settled      : %d" % routed)
    print("    UNREAD : %d" % len(unread))
    gen_total = sum(len(v) for v in gen_hits.values())
    if gen_total:
        print()
        print("  %d same-line match(es) on GENERATED AGGREGATION PAGES - join not applied, since" % gen_total)
        print("  a generator concatenates unrelated documents onto one line and rewrites the page")
        print("  wholesale; a durable absence claim lives on an authored page:")
        for t in TYPES:
            for rel, n, phrase, line, _dig in gen_hits.get(t, []):
                print("      %-28s %s:%d   (\"%s\")" % (t, rel, n, phrase))

    # A KEY THAT MATCHES NOTHING LOOKS EXACTLY LIKE A KEY THAT WAS NEVER NEEDED, which is how three
    # of the six readings above went dead without a word. Now it is said out loud: a reading whose
    # line no longer exists in the corpus has either moved beyond recognition or been reworded, and
    # either way it is no longer clearing anything.
    seen = set()
    for t in TYPES:
        for rel, _n, _p, _l, dig in hits.get(t, []):
            seen.add((rel.replace("\\", "/"), dig))
    dead = [k for k in READ if k not in seen]
    if dead:
        print()
        print("  %d recorded reading(s) MATCH NOTHING in the corpus - the line was reworded or" % len(dead))
        print("  removed, so the reading no longer clears anything and should be re-read or deleted:")
        for rel, dig in sorted(dead):
            print("      %s   evidence %s" % (rel, dig))
    if not total:
        print()
        print("  NONE. The gap is real and unexercised: no published claim leans on a census that")
        print("  could not have seen the write. Nothing is retracted; what follows is that these")
        print("  censuses must be completed BEFORE any such claim is made, not that any existing")
        print("  one is wrong.")
    # A VERDICT, NOT A CONSTANT. This file ended `return 0` unconditionally - it found four hits in
    # September and returned 0, and thirteen today and returned 0. A tool that answers "does any
    # published claim lean on a blind census" with a constant answers nothing.
    if unread:
        print()
        print("  A PUBLISHED ABSENCE CLAIM ABOUT A BLIND-CENSUS TYPE HAS NOT BEEN READ.")
        print("  Each is a QUESTION for the document's owner - the claim may rest on a code")
        print("  reading that holds it up perfectly well - but it cannot stand unexamined, which")
        print("  is the whole reason this file exists.")
        for t, rel, n, phrase, line in unread:
            print("    %-24s %s:%d  (\"%s\")" % (t, rel, n, phrase))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
