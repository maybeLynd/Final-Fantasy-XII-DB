"""gen_pass22_ranked.py - FINAL-AUDIT pass 22 is not 1,062 equal problems.

**Pass 22 is the single MECHANISED pass that would fail today.** `final_audit_verdicts` reads 27
passes clean, 1 PARTIAL and honestly so (pass 5, which needs an independent Ghidra headless import),
1 with no instrument by design (pass 13, "re-derive each mechanism without reading the document" -
a pass whose whole content is that a person did it blind), and **pass 22 RED**.

Red on 1,062 UNACCOUNTED NEIGHBOUR findings: a document cites an address, that address has call
edges to or from some layer, and the document never mentions the layer. There is **no per-document
disposition mechanism** in `audit_crossrefs` - no way to record "this neighbour is out of scope for
this page, and here is why" - so every finding is reported forever and the pass cannot pass until
1,023 documents each gain a mention. That is the shape four other gates had today; the fix there was
a named disposition with a control, and **it is deliberately NOT proposed here**, because a
threshold that makes 514 findings disappear is weakening the test, not adjudicating it.

WHAT THIS DOES INSTEAD IS SIZE THE WORK, because the population is extremely skewed:

    exactly one edge       324 findings   31.7 %
    two or fewer           514 findings   50.2 %
    the top 10 % by edges  102 findings   carrying 3,488 of 6,808 edges - HALF

**Half the unaccounted edges are in a tenth of the findings.** A ranked list turns "1,062 findings"
into "read 102 and half of it is accounted for", which is a program somebody can start.

A HYPOTHESIS THAT FAILED, recorded because it was the obvious one. I expected the residual pages to
dominate - documents whose subject IS unexplained code, flagged for having unexplained neighbours,
close to tautological. They do not: **39 of 1,062**. The finding is corpus-wide and every category
carries it, led by 00-Engine-Core-Runtime (136), 16-UI (116) and 17-Presentation-Rendering (109).

THE INPUT IS THE AUDITOR'S OWN OUTPUT, on purpose. This parses `audit_crossrefs.py`'s markdown rather
than re-implementing its rule, so the ranking can never disagree with the pass it is ranking. The
cost is a coupling to that output's format, and the row shape is asserted on every run: a row that
does not parse is counted and reported, never silently dropped.
"""
import argparse
import collections
import io
import os
import re
import subprocess
import sys

KIT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(KIT))))
DB = os.path.join(REPO, "Database", "FFXII TZA")
GRAPH = os.path.join(REPO, "Database", "Tools", "work", "graph")
ROW = re.compile(r"^- \*\*(?P<doc>.+?)\*\* — `(?P<sub>[^`]+)` — (?P<n>\d+) edge\(s\)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DB)
    ap.add_argument("--functions", default=os.path.join(GRAPH, "functions.tsv"))
    ap.add_argument("--edges", default=os.path.join(GRAPH, "edges.tsv"))
    a = ap.parse_args()
    for p in (a.functions, a.edges):
        if not os.path.isfile(p):
            print("CANNOT RUN: %s is not in the tree" % p)
            return 2
    r = subprocess.run([sys.executable, os.path.join(KIT, "audit_crossrefs.py"),
                        "--docs", a.db, "--functions", a.functions, "--edges", a.edges],
                       capture_output=True, text=True)
    text = r.stdout + r.stderr
    rows, unparsed = [], 0
    inside = False
    for line in text.split("\n"):
        if line.startswith("## "):
            inside = line.strip() == "## UNACCOUNTED NEIGHBOUR"
            continue
        if not inside or not line.startswith("- **"):
            continue
        m = ROW.match(line)
        if not m:
            unparsed += 1
            continue
        rows.append((int(m.group("n")), m.group("doc").replace("\\", "/"), m.group("sub")))
    if not rows:
        print("NO ROWS PARSED - audit_crossrefs' output shape has changed, or the pass is clean.")
        print("  (%d '- **' lines in the section did not parse)" % unparsed)
        return 2
    rows.sort(key=lambda t: (-t[0], t[1], t[2]))
    total_edges = sum(n for n, _d, _s in rows)
    resid = [t for t in rows if t[1].startswith("99-Unresolved-Residual")]
    ordinary = [t for t in rows if not t[1].startswith("99-Unresolved-Residual")]
    ord_edges = sum(n for n, _d, _s in ordinary)
    top = ordinary[:max(1, len(ordinary) // 10)]

    out = [
        "# FINAL-AUDIT pass 22, ranked by edge count - the single mechanised pass that fails today.",
        "#",
        "# Generated by gen_pass22_ranked.py, which parses audit_crossrefs.py's own output rather",
        "# than re-implementing its rule, so this ranking cannot disagree with the pass it ranks.",
        "#",
        "# A finding is: this document cites an address, that address has call edges to or from",
        "# this layer, and the document never mentions the layer. audit_crossrefs has NO",
        "# per-document disposition, so a finding that is legitimately out of scope for its page",
        "# is reported forever. NO THRESHOLD IS PROPOSED HERE - one that made the 514 one-and-two",
        "# edge findings disappear would be weakening the test rather than adjudicating it.",
        "#",
        "# The ranking is the point: half the unaccounted edges sit in a tenth of the findings.",
        "#",
        "# edges\tdocument\tunmentioned_layer",
    ]
    for n, d, s in rows:
        out.append("%d\t%s\t%s" % (n, d, s))
    dest = os.path.join(a.db, "_index", "candidates", "pass22-unaccounted-neighbours.tsv")
    io.open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

    print("FINAL-AUDIT PASS 22, SIZED\n")
    print("  findings                      : %d   (%d edges)" % (len(rows), total_edges))
    print("  on 99-Unresolved-Residual     : %d   <- the obvious hypothesis, and it FAILED"
          % len(resid))
    print("  on ordinary subject pages     : %d   (%d edges)" % (len(ordinary), ord_edges))
    if unparsed:
        print("  ROWS THAT DID NOT PARSE       : %d   <- reported, never dropped" % unparsed)
    buckets = collections.Counter()
    for n, _d, _s in ordinary:
        buckets["1" if n == 1 else "2" if n == 2 else "3-5" if n <= 5 else "6-10" if n <= 10
                else "11-25" if n <= 25 else "26-50" if n <= 50 else "51+"] += 1
    print()
    for b in ("1", "2", "3-5", "6-10", "11-25", "26-50", "51+"):
        print("    %-6s edges : %4d findings (%.1f%%)"
              % (b, buckets[b], 100.0 * buckets[b] / len(ordinary)))
    print("\n  the top 10%% of findings by edge count : %d findings carrying %d of %d edges"
          % (len(top), sum(n for n, _d, _s in top), ord_edges))
    bysub = collections.Counter(s for _n, _d, s in ordinary)
    print("\n  layers most often unmentioned:")
    for k, v in bysub.most_common(8):
        print("    %-28s %4d" % (k, v))
    print("\n  wrote %s" % os.path.relpath(dest, REPO).replace(os.sep, "/"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
