#!/usr/bin/env python3
"""census_archive_formats.py - derive the shipped-file-format population from the archive listing.

Why this exists
---------------
`container_format:` was **counted and not scored** for one stated reason: *"no censused universe of
container formats exists, so a percentage would be invented."*  That reason has now been removed.
`FFXII_TZA.vbf` carries a complete index of everything the game ships, so the population of file
formats is not a matter of opinion -- it is a `GROUP BY` over 89,413 entries.

**This produces the denominator; it does not choose it.**  Every extension present in the archive is
in the population, including the ones nobody will ever write a sheet for.  The disposition of a
format (explained / standard / external) is declared per document and audited; it is NOT applied
here, because a census that pre-excludes the boring rows is an author choosing their own
denominator, which is the exact failure `check_ebp.py` was built to avoid.

What each row records
---------------------
    ext           the extension, lowercased, or `(none)`
    files         how many archive entries carry it
    bytes         total uncompressed size of those entries
    top_dirs      the archive directories they live in, most populous first

**`top_dirs` is evidence, not decoration.**  The archive splits into `ps2data/` (the original game
data), `gamedata/d3d11/` (assets specific to this remaster), `jsondata/` and `prefetchdata/`, and a
format's directory is the strongest cheap signal of which engine subsystem owns it: `.sab` lives in
`ps2data/sound`, `.efx` in `ps2data/effect_finish`, `.phyre` in `gamedata/d3d11`.  Owner assignment
in `_index/ASSET-FORMATS.md` cites this column, so it is carried here rather than re-derived.

Usage
-----
    python census_archive_formats.py --list Tools/work/repos-2d/vbf_list.txt \
                                     --out  Tools/work/formats/archive-extension-census.tsv
    python census_archive_formats.py --self-test
"""
import argparse
import collections
import io
import os
import re
import sys

EXT = re.compile(r"\.([A-Za-z0-9]+)$")


def census(lines):
    """listing lines of `<size> <path>` -> {ext: (files, bytes, Counter(dir))}"""
    files = collections.Counter()
    total = collections.Counter()
    dirs = collections.defaultdict(collections.Counter)
    for line in lines:
        line = line.rstrip("\n")
        if not line.strip():
            continue
        head, _, path = line.partition(" ")
        try:
            size = int(head)
        except ValueError:
            continue
        path = path.strip().lower().replace("\\", "/")
        if not path:
            continue
        parts = path.split("/")
        name = parts[-1]
        m = EXT.search(name)
        ext = m.group(1) if m else "(none)"
        # Two path segments is the useful granularity: `ps2data/sound` separates the subsystems,
        # while the full directory would scatter one format over hundreds of per-area folders.
        d = "/".join(parts[:2]) if len(parts) >= 3 else (parts[0] if len(parts) >= 2 else "/")
        files[ext] += 1
        total[ext] += size
        dirs[ext][d] += 1
    return {e: (files[e], total[e], dirs[e]) for e in files}


def write_tsv(rows, path, source, entries):
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# archive format census - generated by census_archive_formats.py\n")
        f.write("# source: %s\n" % source)
        f.write("# entries: %d   distinct extensions: %d\n" % (entries, len(rows)))
        f.write("# This is the DENOMINATOR for progress.py's `formats_explained`. It is a census\n")
        f.write("# of what ships, not a list of what is worth documenting. Regenerate it, never\n")
        f.write("# hand-edit it; a denominator an author can type is not a denominator.\n")
        f.write("ext\tfiles\tbytes\ttop_dirs\n")
        for ext, (n, b, d) in sorted(rows.items(), key=lambda kv: (-kv[1][0], kv[0])):
            top = ", ".join("%s (%d)" % (k, v) for k, v in d.most_common(3))
            f.write("%s\t%d\t%d\t%s\n" % (ext, n, b, top))


SELF = [
    "100 gamedata/d3d11/a/b.phyre",
    "200 ps2data/sound/x.sab",
    "300 ps2data/sound/y.sab",
    "50 ps2data/square_ff12",
    "not-a-size ps2data/junk.bin",
    "",
]


def self_test():
    r = census(SELF)
    ok = True
    if r["sab"][0] != 2 or r["sab"][1] != 500:
        print("SELF-TEST FAILED: sab %s" % (r["sab"][:2],)); ok = False
    if r["sab"][2].most_common(1)[0][0] != "ps2data/sound":
        print("SELF-TEST FAILED: sab dir %s" % r["sab"][2]); ok = False
    if "(none)" not in r:
        print("SELF-TEST FAILED: extensionless entry dropped"); ok = False
    if "bin" in r:
        print("SELF-TEST FAILED: unparseable size line was counted"); ok = False
    if not ok:
        return 1
    print("self-test ok: sizes summed, two-segment directory kept, extensionless entry counted, "
          "malformed line skipped rather than guessed")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--list")
    ap.add_argument("--out")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    if not (a.list and a.out):
        return ap.error("--list and --out required")
    lines = io.open(a.list, encoding="utf-8", errors="replace").read().split("\n")
    rows = census(lines)
    write_tsv(rows, a.out, os.path.basename(a.list), sum(v[0] for v in rows.values()))
    print("%d entries, %d distinct extensions -> %s"
          % (sum(v[0] for v in rows.values()), len(rows), a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
