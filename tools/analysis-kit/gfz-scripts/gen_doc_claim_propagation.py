import os as _os
import sys as _sys

# The repository root, four levels above this file: gfz-scripts -> analysis-kit -> Tools -> Database
_os.chdir(_os.path.dirname(_os.path.dirname(_os.path.dirname(_os.path.dirname(
    _os.path.dirname(_os.path.abspath(__file__)))))))

# The original module docstring, kept verbatim:
# triage_doc_claims.py - split check_doc_claims' 33 hits into formatting variance and real absence.
#
# check_doc_claims matches the quoted term LITERALLY in the target document. Several of its hits
# look like the same fact written differently: `+0x038` against `+0x38`, a term wrapped in brackets
# or backticks, spacing around an arrow. Those are not propagation defects.
#
# This re-tests each hit against the target under progressively weaker matching and reports which
# band each lands in. Weakening the match is fine HERE because nothing is being closed on it: the
# bands are a triage for reading, and a term that survives every band is the one to actually read.
#
# Run from the repo root.

import io, os, re, subprocess, sys, collections

DB = "Database/FFXII TZA"
KIT = "Database/Tools/analysis-kit/gfz-scripts"

r = subprocess.run([sys.executable, os.path.join(KIT, "check_doc_claims.py"), "--db", DB],
                   capture_output=True, text=True)
out = r.stdout or ""

hits = []
citing = None
for line in out.split("\n"):
    m = re.match(r"^  (\S.*\.md)\s*$", line)
    if m:
        citing = m.group(1).strip()
        continue
    m = re.match(r"^      -> (\S.*\.md)\s+missing term: '(.*)'\s*$", line)
    if m and citing:
        hits.append((citing, m.group(1).strip(), m.group(2)))

print("parsed %d hits from check_doc_claims\n" % len(hits))


def norm_light(s):
    """backticks, brackets and whitespace only."""
    s = s.replace("`", "").replace("[", "").replace("]", "")
    return re.sub(r"\s+", " ", s).strip().lower()


def norm_addr(s):
    """also normalise hex offsets: +0x038 -> +0x38, and pad bare addresses to 8 digits."""
    s = norm_light(s)
    s = re.sub(r"\+0x0*([0-9a-f]+)", lambda m: "+0x" + m.group(1), s)
    s = re.sub(r"(?<![0-9a-z])0*([0-9a-f]{6,8})(?![0-9a-z])",
               lambda m: m.group(1).lstrip("0").rjust(8, "0"), s)
    return s


def norm_hard(s):
    """drop every non-alphanumeric - the last resort before calling a term absent."""
    return re.sub(r"[^0-9a-z]", "", norm_addr(s))


bands = collections.Counter()
rows = []
for citing, target, term in hits:
    p = os.path.join(DB, target.replace("\\", os.sep))
    if not os.path.exists(p):
        rows.append((citing, target, term, "TARGET-MISSING"))
        bands["TARGET-MISSING"] += 1
        continue
    t = io.open(p, encoding="utf-8", errors="replace").read()
    if norm_light(term) and norm_light(term) in norm_light(t):
        band = "punctuation only"
    elif norm_addr(term) and norm_addr(term) in norm_addr(t):
        band = "address form"
    elif norm_hard(term) and norm_hard(term) in norm_hard(t):
        band = "wording/spacing"
    else:
        band = "ABSENT - read it"
    bands[band] += 1
    rows.append((citing, target, term, band))

print("BANDS")
for k in ("punctuation only", "address form", "wording/spacing", "ABSENT - read it", "TARGET-MISSING"):
    if bands[k]:
        print("   %-20s %d" % (k, bands[k]))

print("\nSURVIVES EVERY NORMALISATION - these are the real propagation questions:")
n = 0
for citing, target, term, band in rows:
    if band in ("ABSENT - read it", "TARGET-MISSING"):
        n += 1
        print("\n  %d. %s" % (n, citing))
        print("     -> %s" % target)
        print("     term: %s" % term[:100])

io.open("Database/Tools/work/OPUS/doc_claims_triage.tsv", "w", encoding="utf-8", newline="\n").write(
    "citing\ttarget\tband\tterm\n" +
    "".join("%s\t%s\t%s\t%s\n" % (c, t, b, term.replace("\t", " ")) for c, t, term, b in rows))
print("\nwrote Database/Tools/work/OPUS/doc_claims_triage.tsv")
