"""gen_residual_split.py - splits the ledger residuals by how deeply the corpus reads each one.

PUBLISHED INTO THE KIT 2026-09-14 from `Tools/work/OPUS/build_residual_split.py`, which `.gitignore` excludes.
A canonical candidates file under `_index/candidates/` named it in its header, so the instruction
for reproducing a file this corpus cites pointed at a tool no peer had. Found by extending
`check_cited_instruments.py` to side files - it had been closed over `_index/*.md` and the kit's own
`*.py` and was blind to `.tsv` entirely.

THE BODY BELOW IS THE ORIGINAL, UNCHANGED. Rewriting its paths and defaults while publishing it
would mean the tool in the kit is not the tool that produced the file beside it, and seeing how the
rows were derived is the whole reason for publishing. The only addition is the two lines under this
docstring, which resolve the repository root from `__file__` and change into it so the tool's
repo-relative paths mean what they have always meant, from any working directory.

NAMED `gen_*`, NOT `check_*`: `run_gates.py` globs `check_*.py`, and a generator under that prefix
would run as a gate every suite and rewrite its own output as a side effect of auditing.

> **DO NOT RUN THIS WITHOUT READING THE NEXT SENTENCE.** GENERATION-BOUND. It reads `Tools/work/verify/residual_addrs.txt`, which holds GN160's 139 residuals; the certified parent's set is 30. Its output is named `residual-139-explanation-depth.tsv` and five canonical documents cite it under that name, so it is a GN160-era artifact. Running this today rewrites it against a different generation without saying so.
"""
import os as _os
import sys as _sys

# The repository root, four levels above this file: gfz-scripts -> analysis-kit -> Tools -> Database
_os.chdir(_os.path.dirname(_os.path.dirname(_os.path.dirname(_os.path.dirname(
    _os.path.dirname(_os.path.abspath(__file__)))))))

# The original module docstring, kept verbatim:
# build_residual_split.py - split the 139 ledger residuals by how deeply the corpus reads them.
#
# Writes Database/FFXII TZA/_index/candidates/residual-139-explanation-depth.tsv.
#
# The split is a PROXY and the file says so: an interior citation is evidence that someone read the
# body, not proof that the body is explained. It ranks the 139 for routing; it decides nothing.

import io, os, re, collections

DB = "Database/FFXII TZA"
RES = r"Database\Tools\work\verify\residual_addrs.txt"
FTS = r"Database\Tools\work\graph\functions.tsv"
OUT = os.path.join(DB, "_index", "candidates", "residual-139-explanation-depth.tsv")

res = [l.strip().upper() for l in io.open(RES, encoding="utf-8", errors="replace")
       if re.fullmatch(r"[0-9A-Fa-f]{8}", l.strip())]

fh = io.open(FTS, encoding="utf-8", errors="replace")
head = fh.readline().rstrip("\n").split("\t")
i = {n: k for k, n in enumerate(head)}
size, tags = {}, {}
for ln in fh:
    q = ln.rstrip("\n").split("\t")
    if q and re.fullmatch(r"[0-9A-Fa-f]{8}", q[0]):
        a = q[0].upper()
        try:
            size[a] = int(q[i["body_bytes"]])
        except ValueError:
            size[a] = 0
        tags[a] = q[i["tags"]] if i.get("tags", 99) < len(q) else ""

spans = [(int(a, 16), int(a, 16) + size.get(a, 0), a) for a in res]
ADDR = re.compile(r"(?<![0-9A-Fa-fx.])(0[0-9A-Fa-f]{7})(?![0-9A-Fa-f])")

interior = collections.Counter()
entry = collections.Counter()
pages = collections.defaultdict(set)

for root, dirs, files in os.walk(DB):
    dirs[:] = [d for d in dirs if not d.startswith(".")]
    for fn in files:
        if not fn.endswith(".md"):
            continue
        rel = os.path.relpath(os.path.join(root, fn), DB).replace("\\", "/")
        if rel.startswith("_index/") or rel.startswith("99-Unresolved-Residual/"):
            continue
        t = io.open(os.path.join(root, fn), encoding="utf-8", errors="replace").read()
        for m in ADDR.finditer(t):
            v = int(m.group(1), 16)
            for lo, hi, a in spans:
                if v == lo:
                    entry[a] += 1
                    pages[a].add(rel)
                elif lo < v < hi:
                    interior[a] += 1
                    pages[a].add(rel)


def band(a):
    if interior[a] > 0:
        return "BODY-READ"
    if entry[a] > 0:
        return "ENTRY-MENTION"
    return "UNTOUCHED"


os.makedirs(os.path.dirname(OUT), exist_ok=True)
w = io.open(OUT, "w", encoding="utf-8", newline="\n")
w.write("# The 139 ledger residuals, split by how deeply the corpus reads each one.\n")
w.write("#\n")
w.write("# Generated by Database/Tools/work/OPUS/build_residual_split.py (OPUS, 2026-09-14).\n")
w.write("# Source: Database/Tools/work/verify/residual_addrs.txt - bodies carrying NO\n")
w.write("# GFZ.V121.CodeDomain classification. unresolved = 0 is a hard gate for L1.\n")
w.write("#\n")
w.write("# THE BAND IS A PROXY AND DECIDES NOTHING. An interior citation is evidence that\n")
w.write("# somebody read the body; it is not proof the body is explained, and progress.py says\n")
w.write("# the same of its own interior-citation measure. BODY-READ means 'worth reading the\n")
w.write("# page before assuming this needs new research', not 'already done'.\n")
w.write("#\n")
w.write("# _index/ and 99-Unresolved-Residual/ are excluded from the citation scan: they are\n")
w.write("# where residuals are listed BECAUSE they are residual, so counting them would score\n")
w.write("# every row alike.\n")
w.write("#\n")
w.write("# addr\tbytes\tband\tinterior\tentry\tpages\n")
order = {"BODY-READ": 0, "ENTRY-MENTION": 1, "UNTOUCHED": 2}
for a in sorted(res, key=lambda x: (order[band(x)], -interior[x], -size.get(x, 0))):
    w.write("%s\t%d\t%s\t%d\t%d\t%s\n" % (a, size.get(a, 0), band(a), interior[a], entry[a],
                                          ";".join(sorted(pages[a]))))
w.close()

c = collections.Counter(band(a) for a in res)
tot = collections.Counter()
for a in res:
    tot[band(a)] += size.get(a, 0)
print("wrote %s" % OUT)
for k in ("BODY-READ", "ENTRY-MENTION", "UNTOUCHED"):
    print("  %-14s %3d functions  %7d B" % (k, c[k], tot[k]))
# control: do any of the 139 already carry a CodeDomain tag?
bad = [a for a in res if "GFZ.V121.CodeDomain" in (tags.get(a) or "")]
print("  CONTROL - residuals that already carry a CodeDomain tag: %d (expect 0)" % len(bad))
