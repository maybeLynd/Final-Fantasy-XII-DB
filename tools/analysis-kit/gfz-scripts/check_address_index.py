#!/usr/bin/env python3
"""check_address_index.py - the generated address index against what the corpus actually cites.

`ADDRESS-INDEX.md` is GENERATED by `gen_address_index.py`, and **nothing verified that the committed
file still matches what the generator produces.** Measured today before this file existed: the index
said 13,475 addresses and the corpus cites 13,476, with 48 rows changed and 69 added - ordinary
drift from other people's edits, accumulating silently.

That matters because of what the index is for, in its own words:

> **A hand-maintained index that has fallen two orders of magnitude behind is worse than no index:
> a reader who looks up an address and finds nothing concludes the database does not cover it.**

It fell two orders of magnitude once already. Generating it fixed that and left the loop open.

WHAT FAILS, AND WHY IT IS NOT A THRESHOLD. Row order and header counts drift on every commit that
adds a citation, and a gate that failed on those would be red permanently and become wallpaper -
the failure this kit has had to correct four times. So the split is by what MISLEADS A READER, not
by how much changed:

  MISSING ADDRESS   a document cites it and the index does not list it. The reader looks it up,
                    finds nothing, and concludes the database does not cover it. FAILS - but only
                    if the citation is OLDER than the index; see below.
  NOT YET OWED      the citing document was published AFTER the index was last committed. Eight
                    agents publish into this tree: four minutes after a green run, a peer's page
                    put thirteen new addresses in front of this checker. That is the queue, not
                    debt. Reported, does not fail.
  STALE POINTER     the index sends the reader to a document that no longer cites the address.
                    Worse than silence, because it looks like an answer. FAILS.
  INCOMPLETE ROW    the address is listed, and a further document now cites it too. The reader is
                    sent somewhere true and not everywhere true. Reported, does not fail.
  HEADER COUNTS     cosmetic. Reported, does not fail.

**And the remedy is one command**, which is why failing is reasonable here where it is not for a
debt report: `gen_address_index.py --db <db> --out <the file>`.

DOES THE INDEX OWE THIS ROW YET. The index owes a row for every citation that existed when it was
last committed; one published afterwards clears on the next regeneration and is not this file's
finding. So each missing address is timed - `git log -1 --format=%ct` on the index and on its citing
documents - and only the ones older than the index fail. Both directions are proven on a synthetic
repository whose timeline the control owns (`Tools/work/OPUS/control_index_owes.py`), because on the
live database only one of them can be observed at a time. Above `OWED_CAP` missing rows the timing
is skipped and all of them fail: at that size it is not a queue, it is a destroyed index.

THE GENERATOR IS RUN, NOT RE-IMPLEMENTED, so this can never disagree with the thing it checks. A
run that produces no parsable rows exits 2 rather than reporting a clean index, and **a run whose
generator exited non-zero exits 2 as well** - that same control caught this file regenerating into
one fixed temp path, finding the file there after a refusal, and comparing the committed index
against THE PREVIOUS RUN'S output. A comparison against a file the current run did not produce is
not a comparison.
"""
import argparse
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile

KIT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(KIT))))
DB = os.path.join(REPO, "Database", "FFXII TZA")
# Above this many missing rows, the timing is skipped and every one fails: at that size it is not
# a publication queue, it is a destroyed index - ec044d8f deleted 26,094 rows - and 4,300 `git log`
# calls cost more than the answer is worth.
OWED_CAP = 300
ROW = re.compile(r"^\|\s*`(0[0-9A-Fa-f]{7})`\s*\|(.*)\|\s*$", re.M)
LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")


def tracked_files(db):
    """The files git actually has. -> set of db-relative paths, or None if git is unavailable.

    THE INDEX DESCRIBES THE REPOSITORY. gen_address_index scans the WORKING TREE, so an untracked
    file's addresses land in one agent's regeneration and not another's - which is how this checker
    came to report the same twenty addresses as "missing" across two peer regenerations that had
    removed them. A row nobody else can produce is not a row the index owes.
    """
    import subprocess
    try:
        r = subprocess.run(["git", "ls-files", "-z"], cwd=db, capture_output=True, timeout=120)
    except Exception:
        return None
    if r.returncode != 0:
        return None
    return {p.decode("utf-8", "replace").replace("\\", "/")
            for p in r.stdout.split(b"\0") if p}


def tracked_citers(db, addrs, tracked):
    """Which of `addrs` are cited by a TRACKED file. -> set of addresses. ONE pass over the corpus.

    RESTRICTED TO THE POPULATION THE GENERATOR WALKS - numbered category folders. The first version
    searched the whole database and found `0080C440` in `_index/candidates/static-init-form-530.tsv`,
    which IS tracked, and so reported it as genuinely missing from an index that never indexes
    `_index/` at all. **A checker that asks a wider question than the generator answers reports the
    difference as the generator's fault.**

    AND IT WAS ONE PASS PER ADDRESS, which is the other thing that went wrong. Re-walking 4,300
    files for each missing address pushed a 3-second check past ten minutes, in a suite `run_gates`
    runs end to end. One pass, all addresses, a single compiled alternation.
    """
    if not addrs:
        return set()
    pat = re.compile(r"\b(" + "|".join(sorted(addrs)) + r")\b", re.I)
    found = set()
    for root, _d, files in os.walk(db):
        top = os.path.relpath(root, db).split(os.sep)[0]
        if not re.match(r"^\d\d-", top):
            continue
        for fn in files:
            if not (fn.endswith(".md") or fn.endswith(".tsv")):
                continue
            rel = os.path.relpath(os.path.join(root, fn), db).replace(os.sep, "/")
            if tracked is not None and rel not in tracked:
                continue
            try:
                t = io.open(os.path.join(root, fn), encoding="utf-8", errors="replace").read()
            except OSError:
                continue
            for m in pat.finditer(t):
                found.add(m.group(1).upper())
            if len(found) == len(addrs):
                return found
    return found


def commit_times(db, rels):
    """{db-relative path: unix time of its last commit}, and 0 for anything git has no commit for.

    THE AMBIENT GIT ENVIRONMENT IS STRIPPED for the same reason the generator strips it: with
    GIT_DIR set and no GIT_WORK_TREE, git answers about the repository root and every path here
    misses.
    """
    env = dict(os.environ)
    for var in ("GIT_INDEX_FILE", "GIT_DIR", "GIT_WORK_TREE"):
        env.pop(var, None)
    out = {}
    for rel in rels:
        try:
            r = subprocess.run(["git", "log", "-1", "--format=%ct", "--", rel],
                               cwd=db, capture_output=True, text=True, timeout=60, env=env)
            out[rel] = int(r.stdout.strip()) if r.stdout.strip().isdigit() else 0
        except Exception:
            out[rel] = 0
    return out


def dirty(db, rels):
    """The subset of `rels` with uncommitted local changes. Nobody else can see those yet."""
    env = dict(os.environ)
    for var in ("GIT_INDEX_FILE", "GIT_DIR", "GIT_WORK_TREE"):
        env.pop(var, None)
    try:
        r = subprocess.run(["git", "status", "--porcelain", "-z", "--"] + sorted(rels),
                           cwd=db, capture_output=True, timeout=120, env=env)
    except Exception:
        return set()
    got = set()
    for rec in r.stdout.split(b"\0"):
        s = rec.decode("utf-8", "replace")
        if len(s) > 3:
            got.add(s[3:].strip('"').replace("\\", "/"))
    return got & set(rels)


def rows(text):
    """address -> set of linked document paths. Ignores order, prose and the `table only` note."""
    out = {}
    for m in ROW.finditer(text):
        out[m.group(1).upper()] = {t.replace("\\", "/") for _n, t in LINK.findall(m.group(2))}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DB)
    a = ap.parse_args()
    committed_path = os.path.join(a.db, "_index", "ADDRESS-INDEX.md")
    if not os.path.isfile(committed_path):
        print("CANNOT RUN: no _index/ADDRESS-INDEX.md under %s" % a.db)
        return 2
    gen = os.path.join(KIT, "gen_address_index.py")
    if not os.path.isfile(gen):
        print("CANNOT RUN: gen_address_index.py is not in the kit")
        return 2
    # A FRESH DIRECTORY PER RUN, AND THE EXIT CODE IS READ. This used to regenerate into one fixed
    # path and test only whether a file was THERE. The generator now refuses bad runs (an empty
    # walk, a collapse in row count) and exits non-zero WITHOUT writing - and the checker would
    # then parse THE PREVIOUS RUN'S output and report the difference between the committed index
    # and a regeneration of something else entirely. Caught by a control on a synthetic
    # repository, where it declared 26,112 addresses of the real database missing from an index
    # of two. A comparison against a file the current run did not produce is not a comparison.
    tmpdir = tempfile.mkdtemp(prefix="address-index-regen-")
    tmp = os.path.join(tmpdir, "ADDRESS-INDEX.md")
    try:
        r = subprocess.run([sys.executable, gen, "--db", a.db, "--out", tmp],
                           capture_output=True, text=True)
        if r.returncode != 0:
            print("CANNOT RUN: the generator exited %d and wrote nothing to compare against."
                  % r.returncode)
            print((r.stdout + r.stderr)[-500:])
            return 2
        if not os.path.isfile(tmp):
            print("CANNOT RUN: the generator produced no file")
            print((r.stdout + r.stderr)[-400:])
            return 2
        fresh = rows(io.open(tmp, encoding="utf-8", errors="replace").read())
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)
    have = rows(io.open(committed_path, encoding="utf-8", errors="replace").read())
    if not fresh:
        print("CANNOT RUN: the regenerated index parsed to no rows - the row shape has changed.")
        return 2

    missing_all = sorted(set(fresh) - set(have))
    tracked = tracked_files(a.db)
    by_tracked = tracked_citers(a.db, set(missing_all), tracked)
    missing = [x for x in missing_all if x in by_tracked]
    untracked_only = [x for x in missing_all if x not in by_tracked]
    # DOES THE INDEX OWE THIS ROW YET? A citation published AFTER the index was last generated is
    # not debt, it is the queue - see this file's docstring. Measured: peers put thirteen new
    # addresses in front of this checker in the four minutes between a green run and the suite.
    not_yet = []
    if missing and len(missing) <= OWED_CAP:
        cite = {}
        for addr in missing:
            cite[addr] = {d[3:] if d.startswith("../") else d for d in fresh[addr]}
        docs = sorted({d for v in cite.values() for d in v})
        idx_rel = "_index/ADDRESS-INDEX.md"
        times = commit_times(a.db, docs + [idx_rel])
        local = dirty(a.db, docs)
        idx_t = times.get(idx_rel, 0)
        owed = []
        for addr in missing:
            # The row is owed if ANY citing document was already committed when the index was
            # generated. One old citer is enough to make the absence the index's fault.
            if any(times.get(d, 0) and times[d] <= idx_t and d not in local for d in cite[addr]):
                owed.append(addr)
            else:
                not_yet.append(addr)
        missing = owed

    extra = sorted(set(have) - set(fresh))
    stale_ptr, incomplete = [], []
    for addr in sorted(set(fresh) & set(have)):
        gone = have[addr] - fresh[addr]
        new = fresh[addr] - have[addr]
        if gone:
            stale_ptr.append((addr, sorted(gone)))
        if new:
            incomplete.append((addr, sorted(new)))

    print("THE GENERATED ADDRESS INDEX, AGAINST WHAT THE CORPUS CITES\n")
    print("  rows committed  : %d" % len(have))
    print("  rows regenerated: %d" % len(fresh))
    print()
    if untracked_only:
        print("  cited ONLY by an UNTRACKED file - not the index's to carry : %d"
              % len(untracked_only))
        print("     gen_address_index scans the WORKING TREE, so these land in one agent's")
        print("     regeneration and vanish from another's. The index describes the REPOSITORY;")
        print("     a row nobody else can produce is not a row it owes. Reported, not failed.")
        for addr in untracked_only[:8]:
            print("       %s" % addr)
        print()
    if not_yet:
        print("  cited by a document published SINCE the index was last generated : %d"
              % len(not_yet))
        print("     Not debt - the queue. Eight agents publish into this tree; a generated index")
        print("     is stale minutes after it is written, and a gate that failed on that would be")
        print("     red permanently and become wallpaper. It clears on the next regeneration.")
        for addr in not_yet[:8]:
            print("       %s" % addr)
        print()
    print("  MISSING ADDRESS - cited before the index was generated, and not listed : %d"
          % len(missing))
    for addr in missing[:12]:
        print("     %s   %s" % (addr, ", ".join(sorted(fresh[addr])[:2])[:88]))
    print("  STALE POINTER - listed against a document that no longer cites it : %d"
          % len(stale_ptr))
    for addr, gone in stale_ptr[:12]:
        print("     %s   -> %s" % (addr, ", ".join(gone)[:88]))
    print("  ---- reported, does not fail ----")
    print("  INCOMPLETE ROW - a further document cites it too : %d" % len(incomplete))
    for addr, new in incomplete[:6]:
        print("     %s   + %s" % (addr, ", ".join(new)[:88]))
    print("  ROWS THE INDEX HAS AND THE CORPUS NO LONGER CITES : %d" % len(extra))
    for addr in extra[:6]:
        print("     %s" % addr)

    if missing or stale_ptr:
        print("\n  THE FIX IS ONE COMMAND, which is why this fails where a debt report would not:")
        print("    python gen_address_index.py --db \"%s\" --out \"%s\""
              % (a.db, os.path.join(a.db, "_index", "ADDRESS-INDEX.md")))
        print("  Row order and header counts are NOT checked - they drift on every commit that")
        print("  adds a citation, and failing on those would make this permanently red.")
        return 1
    print("\n  The index lists every cited address and points at no document that has stopped")
    print("  citing one. Order and counts are not checked and may still differ.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
