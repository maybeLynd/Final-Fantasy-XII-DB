"""check_call_chains.py - the one index FINAL-AUDIT pass 29 names that nothing tests.

Pass 29 requires *"`ADDRESS-INDEX`, `CALL-CHAINS`, `COVERAGE`, `OPEN-QUESTIONS` complete and
accurate"*. Three of those four are covered:

    ADDRESS-INDEX   generated by gen_address_index.py, so regenerating and diffing IS the test
    COVERAGE        eight instruments read it
    OPEN-QUESTIONS  ten instruments read it

    CALL-CHAINS     ONE file mentions it, check_novelty_claims.py, and only as a source to read -
                    nothing tests it for anything

So the index the audit must certify as complete and accurate has never been measured. This measures
what can be measured without judgement, and says plainly what cannot.

WHAT IS TESTED
  * every row's Document link points at a file that EXISTS
  * every row either links a document or defers to the previous row's document
  * how many rows claim a CROSSING between owners

WHAT IS DELIBERATELY NOT TESTED
  **The "documented in both directions" claim.** The obvious test -- does the named document mention
  the owner on the other side? -- fails, because owner labels are CodeDomain names like
  `WorldAreaField` or `InputGameplay/UI` and no page writes them as one token. A page entirely about
  WorldAreaField never contains the string. My first version reported 13 of 35 crossings as
  one-sided on exactly that basis and all 13 were the test. Reported as UNTESTED.

WHAT IS NOT TESTED, and is stated rather than implied
  **Completeness against the engine.** "Every cross-subsystem transition" cannot be derived from the
  corpus: nothing enumerates the true set of cross-subsystem transitions, which is the thing the
  database is being written to discover. A proxy IS reported -- documents that live in a
  `call-chains/` directory and are not listed -- because that is the one population where a missing
  row is unambiguous.
"""
import io, os, re, sys, collections

DB = "Database/FFXII TZA"
IDX = os.path.join(DB, "_index", "CALL-CHAINS.md")
ROW = re.compile(r"^\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*$")
LINK = re.compile(r"\[`?([^\]`]+)`?\]\(([^)]+)\)")
ARROW = re.compile(r"->|→")

text = io.open(IDX, encoding="utf-8", errors="replace").read()
rows, cur_doc = [], None
inside = False
for n, line in enumerate(text.split("\n"), 1):
    # ONLY the "Documented chains" table. The file holds six other three-column tables - accessor
    # hubs, the foe-class sightings, the 0x80000003 predicate - and matching every `| a | b | c |`
    # row swept them in and reported 31 of them as having a broken link. They have no Document
    # column at all. Read the SECTION, not the shape. 2026-09-14, OPUS.
    if line.startswith("## "):
        inside = line.strip() == "## Documented chains"
        continue
    if not inside:
        continue
    m = ROW.match(line)
    if not m:
        continue
    chain, owners, doc = m.groups()
    if chain.lower() == "chain" or set(chain) <= set("-: "):
        continue
    rows.append((n, chain, owners, doc))

print("CALL-CHAINS - the index pass 29 names and nothing tests\n")
print("  rows parsed: %d" % len(rows))

missing, resolved, same = [], 0, 0
targets = {}
for n, chain, owners, doc in rows:
    lm = LINK.search(doc)
    if not lm:
        if "same document" in doc.lower():
            same += 1
            targets[n] = None
            continue
        missing.append((n, chain, doc, "no link and not 'same document'"))
        continue
    rel = lm.group(2).split("#")[0]
    p = os.path.normpath(os.path.join(DB, "_index", rel))
    if os.path.exists(p):
        resolved += 1
        targets[n] = p
    else:
        missing.append((n, chain, doc, "link target does not exist: %s" % rel))

print("  rows whose document link resolves        : %d" % resolved)
print("  rows deferring to the previous document  : %d" % same)
print("  rows with a BROKEN or absent link        : %d" % len(missing))
for n, chain, doc, why in missing[:10]:
    print("      line %-5d %s  <- %s" % (n, chain[:60], why))

# THE "BOTH DIRECTIONS" CLAIM IS NOT MECHANICALLY TESTABLE, and saying so beats faking it.
#
# The header promises every transition is "documented in both directions". The obvious test - does
# the named document mention the owner on the other side? - fails because owner labels are
# CodeDomain names like `WorldAreaField`, `InputGameplay/UI` or `CoreRuntimeScheduling`, and no page
# writes them as one token. A page about weather scaling is entirely about WorldAreaField and never
# contains the string. My first version reported 13 of 35 crossings as one-sided on exactly that
# basis; all 13 were the test, not the index.
#
# Testing it properly needs a label -> directory/owner mapping the corpus does not publish, so the
# claim is reported as UNTESTED rather than as passing or failing. 2026-09-14, OPUS.
cross = [(n, c, o, d) for n, c, o, d in rows if ARROW.search(o)]
print("\n  rows claiming a CROSSING (owner -> owner) : %d" % len(cross))
print("      the header's \"documented in both directions\" claim is NOT tested here - owner labels")
print("      are CodeDomain names no page writes as one token, so a text test reports false")
print("      one-sidedness. It needs a label -> owner mapping the corpus does not publish.")
onesided = []

# the completeness proxy
listed = set()
for n, chain, owners, doc in rows:
    lm = LINK.search(doc)
    if lm:
        listed.add(os.path.normpath(os.path.join(DB, "_index", lm.group(2).split("#")[0])))
oncall = []
for root, dirs, files in os.walk(DB):
    if os.path.basename(root).lower() != "call-chains":
        continue
    for f in sorted(files):
        if f.endswith(".md"):
            p = os.path.normpath(os.path.join(root, f))
            if p not in listed:
                oncall.append(os.path.relpath(p, DB).replace(os.sep, "/"))
print("\n  documents in a `call-chains/` directory NOT listed in the index : %d" % len(oncall))
for p in oncall[:10]:
    print("      %s" % p)

bad = len(missing) + len(onesided) + len(oncall)
print("\n  total mechanical defects: %d" % bad)
sys.exit(1 if bad else 0)
