"""Record, on each measurable-only row, that its evidence supports a width and no more.

WHY THIS IS NOT A BULK DISPOSITION, WHICH IS THE OBVIOUS OBJECTION AND MY OWN ROLE'S STANDING RULE.
123 field rows have census accesses at their displacement and every one of those accesses is a move
or an address computation. `gen_description_queue.py` separates them from the describable rows
because a move says WHERE BYTES WENT and nothing about what they are - the rule `insn_class.py`
carries.

Giving 123 rows the same sentence would be a bulk disposition if the sentence made a claim about
each FIELD. It does not. It states a property of the EVIDENCE, and that property is genuinely
uniform across the population - it is what defines the population. The three things that keep it
honest:

  IT GOES IN THE EVIDENCE COLUMN, never the meaning column. A row annotated here is still
  UNDESCRIBED and `gen_description_queue` still counts it as such - the guard added on 2026-09-13
  after a batch of type rationales was written into meanings and made the queue look nine rows
  better than it was.

  IT CARRIES THE COUNT, so the statement is falsifiable per row: "N censused accesses, all moves or
  address computations". Anyone who finds an arithmetic access at that displacement has refuted the
  row, not merely disagreed with it.

  IT IS GENERATED, so it is re-derivable and cannot drift from the census it describes.

What it buys: the next person to read the store learns that this row has been LOOKED AT and its
silence is a measured result, not an oversight. That is a different thing from a blank, and 123
blanks are indistinguishable from 123 pieces of nobody-got-to-it-yet.
"""
import collections
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check_census_widths as ccw
import gen_description_queue as gdq
import insn_class

DB = 'Database/FFXII TZA'
FIELDS = os.path.join(DB, '_types', 'fields.tsv')
MARK = 'EVIDENCE EXHAUSTED FOR MEANING:'


def main():
    apply_it = '--write' in sys.argv
    phyre = gdq.phyre_types()
    kinds = gdq.census_kinds()
    censused = {t for t, _f, _b, _s, _e in ccw.censused_types()}

    lines = io.open(FIELDS, encoding='utf-8', newline='').read().split('\n')
    targets = []
    for i, line in enumerate(lines):
        c = line.split('\t')
        if len(c) < 9:
            continue
        if c[5].strip() and not gdq.rationale_only(c[5]):
            continue
        if c[0] in phyre or c[0] not in censused:
            continue
        try:
            off = int(c[1], 16)
        except ValueError:
            continue
        k = kinds.get((c[0], off))
        if not k or any(k[x] for x in gdq.INFORMATIVE):
            continue
        if MARK in c[8]:
            continue
        targets.append((i, c, sum(k.values()), dict(k)))

    print('--- control: measurable-only rows found: %d ---' % len(targets))
    if not targets:
        print('  Nothing to annotate. If gen_description_queue still reports a measurable-only')
        print('  population, this parser disagrees with it and THAT is the finding.')
        return 2
    spread = collections.Counter()
    for _i, _c, _n, k in targets:
        for cls in k:
            spread[cls] += 1
    print('    instruction classes present across them: %s'
          % ', '.join('%s in %d rows' % (a, b) for a, b in spread.most_common()))
    if 'float' in spread or 'int' in spread or 'const' in spread:
        print('  CONTROL FAILED: an informative class appears in this population, so it is not')
        print('  measurable-only and the annotation below would be false.')
        return 2

    for i, c, n, k in targets:
        note = ('%s all %d censused access(es) at this displacement are moves or address '
                'computations (%s), so the WIDTH is the strongest claim this evidence supports and '
                'the meaning is not derivable from it. Not an oversight - a measured result. '
                'Generated by annotate_measurable_only.py; refuted by any arithmetic access here.'
                % (MARK, n, ', '.join('%s x%d' % (a, b) for a, b in sorted(k.items()))))
        c[8] = (c[8].rstrip() + ' — ' if c[8].strip() else '') + note
        lines[i] = '\t'.join(c)

    if apply_it:
        io.open(FIELDS, 'w', encoding='utf-8', newline='').write('\n'.join(lines))
        print('  annotated %d rows' % len(targets))
    else:
        print('  %d rows WOULD be annotated; pass --write to apply' % len(targets))
    print()
    print('  These rows stay UNDESCRIBED in gen_description_queue: the note is evidence, not a')
    print('  meaning, and the queue guard counts a rationale-only meaning as undescribed anyway.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
