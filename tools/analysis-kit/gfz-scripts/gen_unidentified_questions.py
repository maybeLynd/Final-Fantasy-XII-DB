#!/usr/bin/env python3
"""gen_unidentified_questions.py - the open questions OPEN-QUESTIONS.md cannot index: every UNTICKED per-document checkbox
that carries no question id, listed by category and page with a link and its first line.

Why (2026-09-13, FABLE, answering OPUS-REQ-FABLE-REGISTER-COMPLETENESS): the register is an index of IDENTIFIED questions -
a row needs an id, and issuing an id is the page owner's act. Most open questions live only as un-numbered checkboxes in
their page's 'What is not known' section (600 of 715 when OPUS measured). Rather than mint 600 ids, this generated
companion makes them visible beside the register, and check_questions / progress.py keep counting both halves as before.
Uses check_questions.read_boxes, so a box is read exactly as the questions gate reads it.

Usage:  python gen_unidentified_questions.py --db "Database/FFXII TZA" [--out <db>/_index/UNIDENTIFIED-OPEN-QUESTIONS.md]
Regenerate after any page edit that adds or ticks a checkbox; do not hand-edit the output."""
import argparse, collections, importlib.util, io, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("cq", os.path.join(HERE, "check_questions.py"))
cq = importlib.util.module_from_spec(spec); spec.loader.exec_module(cq)
ap = argparse.ArgumentParser(); ap.add_argument("--db", required=True); ap.add_argument("--out", default=None)
ap.add_argument("--force", action="store_true", help="write even if the result is under half the size of the file it replaces")
a = ap.parse_args()
out = a.out or os.path.join(a.db, "_index", "UNIDENTIFIED-OPEN-QUESTIONS.md")
boxes = cq.read_boxes(a.db)
open_boxes = [b for b in boxes if not b[2]]
unid = [b for b in open_boxes if not b[3]]
by = collections.OrderedDict()
_cache = {}
def full_line(rel, line):
    if rel not in _cache: _cache[rel] = io.open(os.path.join(a.db, rel), encoding="utf-8", errors="replace").read().split("\n")
    s = _cache[rel][line - 1].strip()
    return s if len(s) <= 180 else s[:177].rsplit(" ", 1)[0] + " …"
for rel, line, ticked, ids, first in sorted(unid, key=lambda b: (b[0], b[1])):
    by.setdefault(rel.split("/")[0], collections.OrderedDict()).setdefault(rel, []).append((line, full_line(rel, line)))
def clean(s):
    s = re.sub(r"^\s*-\s*\[ \]\s*", "", s).strip()
    return s.replace("|", "\\|")
lines = ["# Unidentified open questions — generated", "",
         "*Generated by `Database/Tools/analysis-kit/gfz-scripts/gen_unidentified_questions.py`. Do not hand-edit; regenerate.*", "",
         "[OPEN-QUESTIONS.md](OPEN-QUESTIONS.md) indexes questions that carry an id. This file lists the rest: every **unticked**",
         "checkbox on a system page that names no question id. Together the two are the complete open list; the per-page checklists",
         "remain the source. To promote a question into the register, its page owner gives the box an id and adds the row.", "",
         "| | count |", "|---|---:|",
         "| unticked checkboxes | %d |" % len(open_boxes),
         "| … naming a question id, as the questions gate reads a box (its own id, or a bold `**ID.**` reference) | %d |" % (len(open_boxes) - len(unid)),
         "| … carrying no id (listed below) | **%d** |" % len(unid), ""]
for cat, pages in by.items():
    n = sum(len(v) for v in pages.values())
    lines += ["## %s (%d)" % (cat, n), ""]
    for rel, items in pages.items():
        lines.append("- [`%s`](../%s)" % (rel.split("/", 1)[1] if "/" in rel else rel, rel))
        for line, first in items:
            lines.append("  - line %d: %s" % (line, clean(first)))
    lines.append("")
# A WRONG --db IS SILENT: read_boxes walks the database, os.walk yields nothing for a path that does
# not exist, and this file becomes a 729-byte header saying zero questions are open - written over
# the canonical 56,723-byte list at exit 0. Zero checkboxes is a wrong argument, not a corpus whose
# every question is answered; that would be the single largest claim this database has ever made.
if not boxes:
    raise SystemExit("gen_unidentified_questions: no checkboxes found under %s - that is a wrong "
                     "--db, not a corpus with no open questions. Nothing was written." % a.db)
text = "\n".join(lines)
if os.path.isfile(out) and not a.force:
    _had = len(io.open(out, encoding="utf-8", errors="replace").read())
    if _had and len(text) * 2 < _had:
        raise SystemExit("gen_unidentified_questions: REFUSING - %s holds %d bytes and this run "
                         "produced %d, less than half. If the shrink is real, pass --force."
                         % (out, _had, len(text)))
io.open(out, "w", encoding="utf-8", newline="\n").write(text)
print("open boxes %d, with id %d, without id %d -> %s" % (len(open_boxes), len(open_boxes) - len(unid), len(unid), out))
