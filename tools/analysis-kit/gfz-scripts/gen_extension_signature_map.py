"""gen_extension_signature_map.py - `.dat` and `.bin` are not formats, and this says what they are.

WHY IT EXISTS. `check_assets` scores `formats_explained` over 48 EXTENSIONS censused from the
archive index, and two of those rows are the two largest in the archive: `.dat` (2,948 entries,
1.94 GB) and `.bin` (1,439 entries, 2.37 GB). Neither is a format. The full signature censuses
under `Tools/work/formats/` show **21 distinct leading signatures in `.dat` and 59 in `.bin`**, so
the disposition vocabulary the gate accepts - `explained` / `standard` / `external`, each meaning a
sheet that explains THE layout - has no honest value for either. Calling a 59-signature namespace
"explained" would be making a metric agree by weakening what the word means.

WHAT THIS PRODUCES IS A ROUTING MAP, NOT A COVERAGE FIGURE, and the distinction is the whole
reason the column is named the way it is. The test is *does any document contain this four-character
token* - it is a MENTION, not an explanation. `himg` matches `file-size-tables-fst.md`, which lists
file NAMES; that is a mention and not a format sheet. So the "named" totals are an UPPER BOUND on
coverage and are printed as one. The useful half is the other direction: a signature no document
mentions AT ALL is certainly not explained, and those are the rows worth routing.

AND NUMERIC SIGNATURES CANNOT BE TESTED THIS WAY AT ALL. `01 00 00 00` is a count or a version, not
a magic; there is no token to search for. They are reported as NOT-A-TOKEN rather than as unexplained,
because "no document mentions `\\x01\\x00\\x00\\x00`" would be a fact about the search, not about the
corpus - the same over-reach this kit's other checkers keep having to be narrowed out of.

THE SHAPE OF THE TWO EXTENSIONS IS DIFFERENT AND THAT MATTERS FOR ROUTING.
`.dat` is 92.3 % ONE family (`himg`, 2,721 of 2,948) with a small tail, so it is effectively one
format plus stragglers - and `OPUS-REQ-SWE2-DATA-HIMG-LAYOUT` is already routed for exactly that
family. `.bin` is genuinely heterogeneous: `sloc` 436 + `st2e` 407 is 58.6 %, then a long tail of
families of 9 and 2.
"""
import argparse
import collections
import io
import os

KIT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(KIT))))
DB = os.path.join(REPO, "Database", "FFXII TZA")
FORMATS = os.path.join(REPO, "Database", "Tools", "work", "formats")
SKIP = ("_index", "_templates", "_inbox", "_experiments")


def printable_token(sig_hex):
    """A magic is four PRINTABLE BYTES. Decide from the HEX, never from the rendered ascii.

    CORRECTED BEFORE FIRST PUBLICATION. The first version tested `sig_ascii`, where the census
    renders a non-printable byte as `.` - so `40 00 00 00` arrives as `@...`, four printable
    characters, and was classified as a token nobody had documented. It is the number 0x40. That
    put 42 entries - the third-largest `.bin` family - into the "worth routing" list as a mystery
    magic, with five smaller families behind it. Read the bytes, not their rendering.
    """
    try:
        b = bytes.fromhex(sig_hex)
    except ValueError:
        return None
    if len(b) != 4 or any(c < 0x20 or c > 0x7E for c in b):
        return None
    return b.decode("ascii")


def read_census(path):
    rows = [l.rstrip("\n").split("\t") for l in io.open(path, encoding="utf-8", errors="replace")
            if l.strip() and not l.startswith("#")]
    if not rows:
        return []
    h = rows[0]
    try:
        i_sig, i_asc = h.index("sig_hex"), h.index("sig_ascii")
    except ValueError:
        return []
    return [(r[i_sig], r[i_asc]) for r in rows[1:] if len(r) > max(i_sig, i_asc)]


def corpus(db):
    out = {}
    for root, dirs, files in os.walk(db):
        dirs[:] = [d for d in dirs if d not in SKIP]
        for fn in sorted(files):
            if fn.endswith(".md"):
                p = os.path.join(root, fn)
                out[os.path.relpath(p, db).replace(os.sep, "/")] = \
                    io.open(p, encoding="utf-8", errors="replace").read()
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DB)
    a = ap.parse_args()
    docs = corpus(a.db)
    out = [
        "# `.dat` and `.bin` by leading signature - a ROUTING MAP, not a coverage figure.",
        "#",
        "# Generated by gen_extension_signature_map.py over Tools/work/formats/"
        "{dat,bin}-signature-census.tsv.",
        "#",
        "# `mentioned_in` ANSWERS A WEAKER QUESTION THAN IT LOOKS LIKE. It asks whether any document",
        "# contains the four-character token, which is a MENTION and not an explanation - `himg`",
        "# matches file-size-tables-fst.md, which lists file NAMES. So a filled cell is an UPPER",
        "# BOUND on coverage. The load-bearing direction is the empty one: a token no document",
        "# mentions at all is certainly not explained.",
        "#",
        "# NOT-A-TOKEN rows are numeric signatures - a count or a version field, not a magic. There",
        "# is nothing to search for, so they are reported as untestable rather than as unexplained;",
        "# `no document mentions \\x01\\x00\\x00\\x00` would be a fact about the search.",
        "#",
        "# ext\tsig_hex\tsig_ascii\tentries\tshare\tmentioned_in",
    ]
    print("EXTENSION SIGNATURE MAP - .dat and .bin are namespaces, not formats\n")
    for ext, fname in (("dat", "dat-signature-census.tsv"), ("bin", "bin-signature-census.tsv")):
        rows = read_census(os.path.join(FORMATS, fname))
        if not rows:
            print("  %s: census not in the tree (Tools/work/formats/%s)" % (ext, fname))
            continue
        c = collections.Counter(rows)
        total = len(rows)
        named = untestable = unmentioned = 0
        for (sig, asc), n in c.most_common():
            tok = printable_token(sig)
            hit = ""
            if tok:
                for rel, t in docs.items():
                    if ("`%s`" % tok) in t or ("'%s'" % tok) in t or (" %s " % tok) in t:
                        hit = rel
                        break
                if hit:
                    named += n
                else:
                    unmentioned += n
                    hit = "-"
            else:
                untestable += n
                hit = "NOT-A-TOKEN"
            out.append("%s\t%s\t%s\t%d\t%.2f%%\t%s"
                       % (ext, sig, tok or "-", n, 100.0 * n / total, hit))
        print("  .%-4s %5d entries, %2d distinct signatures" % (ext, total, len(c)))
        print("        a document MENTIONS the token   : %5d  (%.1f%% - an UPPER BOUND)"
              % (named, 100.0 * named / total))
        print("        no document mentions it at all  : %5d  <- the rows worth routing"
              % unmentioned)
        print("        numeric, nothing to search for  : %5d  (NOT-A-TOKEN)" % untestable)
        top = c.most_common(1)[0]
        print("        largest family                  : %s x%d (%.1f%%)"
              % (printable_token(top[0][0]) or top[0][0], top[1], 100.0 * top[1] / total))
    dest = os.path.join(a.db, "_index", "candidates", "dat-bin-signature-map.tsv")
    io.open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("\n  wrote %s" % os.path.relpath(dest, REPO).replace(os.sep, "/"))
    print("\n  NEITHER EXTENSION IS COUNTED BY THIS. `formats_explained` scores extensions, and")
    print("  these two rows are namespaces; the honest unit for them is the SIGNATURE FAMILY.")
    print("  Declaring either `explained` to move the metric would be weakening the word.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
