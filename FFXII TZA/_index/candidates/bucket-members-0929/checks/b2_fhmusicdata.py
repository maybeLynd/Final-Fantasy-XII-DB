"""B2 fhmusicdata.bin - layout on the shipped copy; kind-9 index; requester/reader absence evidence is read from the
sweep outputs in this folder (callpairs_run1.txt, nearcall_imm_run.txt, immpair_9_1c.txt), each regenerated by its
own script with a passing positive control."""
import struct, re
from common import *
header()
print("== static: path directory")
check("kind 9 idx 0x1C path (first-language arm)", kind_path(9, 0x1C) == r"PS2Data\image\ff12\common\fhmusicdata.bin", kind_path(9, 0x1C))
# every language arm's kind-9 array holds the same string at the same index (pointer slots found image-wide)
sv = 0x95EC88
slots = []; p = d.find(struct.pack("<Q", sv))
while p >= 0:
    for nm, va, vs, ro, rs in secs:
        if ro <= p < ro + rs: slots.append(va + p - ro)
    p = d.find(struct.pack("<Q", sv), p + 1)
arm_bases = [s - 0x1C * 8 for s in slots]
same_idx = all(cstr(q(b + 8)) and cstr(q(b + 8)).endswith("test_map_ref.bin") for b in arm_bases)
check(f"{len(slots)} pointer slots to the path string, each at index 0x1C of an array whose index 1 is test_map_ref", len(slots) == 10 and same_idx)
print("== corpus")
files = copies("ps2data/image/ff12/**/fhmusicdata.bin")
check("exactly one shipped copy (common/)", len(files) == 1, str(files))
b = open(files[0], "rb").read()
n = struct.unpack_from("<I", b, 0)[0]
offs = struct.unpack_from("<%dI" % n, b, 4)
check(f"u32 count {n}; offset[0] == 4+4*count == {4 + 4 * n:#x}", offs[0] == 4 + 4 * n)
check("offsets strictly ascending with constant stride 22", all(offs[i + 1] - offs[i] == 22 for i in range(n - 1)))
check(f"size arithmetic 4 + 4*{n} + 22*{n} == {len(b)}", 4 + 4 * n + 22 * n == len(b))
recs = [struct.unpack_from("<11H", b, o) for o in offs]
ids = [r[0] for r in recs]
check("word +0 strictly ascending (a key)", all(ids[i] < ids[i + 1] for i in range(n - 1)), str(ids))
for k in range(1, 11):
    vals = sorted(set(r[k] for r in recs)); print(f"  word +{2 * k:#04x}: values {vals}")
check("words +0x0C,+0x0E,+0x12,+0x14 are zero in every record", all(r[6] == r[7] == r[9] == r[10] == 0 for r in recs))
print("== absence evidence (from the sweep outputs)")
cp = open("callpairs_run1.txt").read()
check("callpairs: every call site scanned, no (9,0x1C) constant pair at any call to any target", "0x1c)" not in cp.split("\n", 1)[1].lower() and "next=0x1c" not in cp)
check("callpairs positive controls passed", "FAILS 0" in cp and "CONTROL 0037870A: PASS" in cp)
ni = open("nearcall_imm_run.txt").read()
idhits = [l for l in ni.splitlines() if re.search(r"(mov|lea) (e?[a-z0-9]+d?), (0x1c|\[r[a-z0-9]+ \+ 0x1c\])$", l.split("<-")[-1].strip()) and "rsp" not in l]
check("nearcall_imm: no request-API call is preceded by an id-register load of 0x1C", not idhits, str(idhits))
check("nearcall_imm controls passed (it finds the loop form lea edx,[rbx+0x98] at 00291CF3)", "FAILS 0" in ni and "00291CF3 lea edx, [rbx + 0x98]" in ni)
ip = open("immpair_9_1c.txt").read()
check("immpair: no memory store pair (9,0x1C) in code; no aligned u16/u32 (9,0x1C) pair in .rdata/.data", "code store-pair hits: 0" in ip and all(" 0" == l.rsplit("hits", 1)[1][:2] for l in ip.splitlines() if ("<HH" in l or "<II" in l)))
finish()
