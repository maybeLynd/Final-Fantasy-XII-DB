"""pass22_debt.py - size and attribute FINAL-AUDIT pass 22's UNACCOUNTED NEIGHBOUR debt (OPUS, 2026-09-29).

Since FRONTIER's afbab48c3 (2026-09-22) scoped `doc_accounts_for` to crossing/neighbour sections, pass 22
reads thousands of findings and no board task carries them. This names each finding's page, layer and
edge count, and attributes the page to the lane whose commit CREATED it (the subject prefix of the
`--diff-filter=A` commit), falling back to the folder. It does not judge any pair and clears nothing.

Input is the auditor's own JSON report, so the debt can never disagree with the pass it sizes:
    python audit_crossrefs.py --docs "Database/FFXII TZA" --functions Database/Tools/work/graph/functions.tsv \
        --edges Database/Tools/work/graph/edges.tsv --json <report.json>
(that run also regenerates _index/candidates/pass22-tripwires.tsv; restore it if the run was only to read)

    python pass22_debt.py <report.json> [--out pass22-debt.tsv]

Controls, asserted every run: every UNACCOUNTED NEIGHBOUR row parses (a row that does not is counted and
fails the run); the per-lane totals sum to the row total; a page the auditor names exists in the corpus.
"""
import argparse, collections, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
REPO = os.path.abspath(os.path.join(DB, "..", ".."))
EDGES = re.compile(r"^(\d+) edge\(s\) to/from ")
LANE = re.compile(r"\s*([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*)\s*[:(]")


def creators():
    out = subprocess.run(["git", "-C", REPO, "log", "--diff-filter=A", "--name-only", "--format=@@%s", "--",
                          "Database/FFXII TZA"], capture_output=True, text=True, encoding="utf-8", errors="replace").stdout
    lane, subj = {}, ""
    for l in out.splitlines():
        if l.startswith("@@"):
            subj = l[2:]
            continue
        if l.startswith("Database/FFXII TZA/"):
            m = LANE.match(subj)
            lane[l[len("Database/FFXII TZA/"):]] = m.group(1) if m else ""   # newest first: last write = creation
    return lane


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("report")
    ap.add_argument("--out", default=os.path.join(HERE, "pass22-debt.tsv"))
    a = ap.parse_args()
    rep = json.load(open(a.report, encoding="utf-8"))
    lane = creators()
    rows, bad = [], 0
    for f in rep["findings"]:
        if f[0] != "UNACCOUNTED NEIGHBOUR":
            continue
        m = EDGES.match(f[3])
        if not m or not os.path.isfile(os.path.join(DB, f[1])):
            bad += 1
            continue
        who = lane.get(f[1]) or ("folder:" + f[1].split("/")[0])
        rows.append((f[1], f[2], int(m.group(1)), who))
    rows.sort(key=lambda r: (r[3], r[0], r[1]))
    with open(a.out, "w", encoding="utf-8", newline="\n") as o:
        o.write("# pass22-debt - UNACCOUNTED NEIGHBOUR pairs from one audit_crossrefs report, attributed to the creating lane "
                "(else the folder). Generated by pass22_debt.py; a sizing, not a disposition.\n")
        o.write("document\tlayer\tedges\tcreated_by\n")
        for r in rows:
            o.write("%s\t%s\t%d\t%s\n" % r)
    by = collections.defaultdict(lambda: [0, set(), 0])
    for d, s, n, w in rows:
        k = w if not w.startswith("folder:") else "(no lane - by folder)"
        by[k][0] += 1; by[k][1].add(d); by[k][2] += n
    tot = sum(v[0] for v in by.values())
    for k, v in sorted(by.items(), key=lambda kv: -kv[1][0]):
        print("%-28s pairs %5d  pages %4d  edges %6d" % (k, v[0], len(v[1]), v[2]))
    print("TOTAL pairs %d pages %d edges %d  unparsed %d" % (tot, len({r[0] for r in rows}), sum(r[2] for r in rows), bad))
    assert tot == len(rows)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
