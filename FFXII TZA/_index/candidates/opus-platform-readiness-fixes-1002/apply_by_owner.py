import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import apply_20platform as base  # noqa: E402

F = "20-Platform-Online-Achievements/"
OWNERS = {
    "FABLE": {
        F + "CONTRACT-steam-integration-subsystem.md",
    },
    # No overlay carrier and no held OPUS page at drafting (see above); kept so both owners run and report 0.
    "SWE2-FRONTIER": set(),
    "OPUS-HELD": set(),
}
LINE_OWNERS = {
    "SWE2-CONTRACT": ("  | 4 | `00315FDC`",
                      "  | 5 | `00315FEB`",
                      "  | 6 | `00315FFA`",
                      "  | 7 | `0031607D`"),
    "SWE2-DATA": ("| `007A1CD0` | `SteamController_PollState`",
                  "      dead through the engine"),
}


def owner_of(e):
    for o, prefixes in LINE_OWNERS.items():
        if e[1].startswith(prefixes):
            return o
    for o, pages in OWNERS.items():
        if e[0] in pages:
            return o
    return "OPUS"


def main():
    owner = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("--") else "OPUS"
    if owner in ("OPUS", *OWNERS, *LINE_OWNERS):
        keep = [e for e in base.EDITS if owner_of(e) == owner]
    else:
        print("unknown owner", owner); print("FAILS 1"); return 1
    print("owner", owner, "edits", len(keep), "of", len(base.EDITS))
    base.EDITS = keep
    return base.main()


if __name__ == "__main__":
    sys.exit(main())
