import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "Tools", "analysis-kit", "gfz-scripts")))
import family_prover as fp  # noqa: E402
from capstone import Cs, CS_ARCH_X86, CS_MODE_64  # noqa: E402

CHECKS = [
    (0x002DF7BF, 'mov', 'rax, qword ptr [r15 + rbx*8 + 0x203f000]'),
    (0x003EA852, 'lea', 'r8d, [rsi + 1]'),
    (0x0023A1AF, 'xor', 'r8d, r8d'),
    (0x002EB7A3, 'ja', '0x2eb7d1'),
    (0x00324629, 'mov', 'r9d, dword ptr [rbx]'),
    (0x00431121, 'cmp', 'al, 2'),
    (0x002FC58C, 'mov', 'ecx, 0xb'),
    (0x0019EB94, 'lea', 'r14, [rax + 0x120]'),
    (0x002806CA, 'cmp', 'rbx, 0x388'),
    (0x002C8F18, 'lea', 'edx, [rdi + 0x74]'),
    (0x002492F3, 'call', '0x32e620'),
    (0x00575CD2, 'mov', 'byte ptr [rbp + 0xd2], cl'),
]


def main():
    d, off = fp.load_image()
    md = Cs(CS_ARCH_X86, CS_MODE_64)
    fails = 0
    for va, mn, ops in CHECKS:
        ins = next(md.disasm(d[off(va):off(va) + 16], va), None)
        ok = ins is not None and ins.mnemonic == mn and ins.op_str == ops
        fails += 0 if ok else 1
        got = "%s %s" % (ins.mnemonic, ins.op_str) if ins else "<no decode>"
        print("%s %08X %s" % ("ok  " if ok else "FAIL", va, got))
    print("FAILS", fails)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
