import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import apply_25ebp as base  # noqa: E402

F = "25-EBP-Script-Container/"
OWNERS = {
    # Every 25-EBP page is OPUS-led by commit count (2026-10-02).
    "FABLE": set(),
    # Overlay carriers go to SWE2-FRONTIER whatever the commits say; scope_guard reports none in 25-EBP (2026-10-02).
    "SWE2-FRONTIER": set(),
    # Generator output: the census TSV is regenerated by SWE2-DATA (gen_req_channel_census.py), never hand-edited;
    # no TSV edit is drafted, so this set carries no edit (OPUS, 2026-10-02).
    "SWE2-DATA": {
        F + "Bytecode-And-Opcodes/members/req-channel-census.tsv",
    },
    # No OPUS page is named by an ACTIVE task of another lane that audits or edits it (TEAM.json, 2026-10-02).
    "OPUS-HELD": set(),
}
LINE_OWNERS = {
    "SWE2-EC7": ("(stored at `0233A6F0 + lane*8`)",),
    "SWE2-DATA": ("`REQCHG`/`REQCANCEL`/`REQALL`/`REQIALL`\n",),
}


def owner_of(e):
    for o, prefixes in LINE_OWNERS.items():
        if e[1].startswith(prefixes):
            return o
    for o, pages in OWNERS.items():
        if e[0] in pages:
            return o
    return "OPUS"


def main():
    owner = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("--") else "OPUS"
    if owner in ("OPUS", *OWNERS, *LINE_OWNERS):
        keep = [e for e in base.EDITS if owner_of(e) == owner]
    else:
        print("unknown owner", owner); print("FAILS 1"); return 1
    print("owner", owner, "edits", len(keep), "of", len(base.EDITS))
    base.EDITS = keep
    return base.main()


if __name__ == "__main__":
    sys.exit(main())
