"""render_c_check.py - the instructions behind the 17-Render readiness corrections, part C (counts and stale items) (OPUS, 2026-10-02). FAILS n.
Generated by Tools/work/OPUS/make_check.py from the verdict table; each line is an instruction the verdicts quote.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "Tools", "analysis-kit", "gfz-scripts")))
import family_prover as fp  # noqa: E402
from capstone import Cs, CS_ARCH_X86, CS_MODE_64  # noqa: E402

CHECKS = [
    (0x0041D5E7, 'call', '0x3b5d40'),
    (0x001FBDB6, 'mov', 'edx, 8'),
    (0x001DB875, 'mov', 'edx, 0x640'),
    (0x004268A3, 'call', 'rsi'),
    (0x001FA748, 'call', 'qword ptr [rax + 0x68]'),
    (0x001F5F38, 'call', '0x60b980'),
    (0x00427DB3, 'or', 'dword ptr [rdi + 0x48818], 0x20'),
    (0x0041F754, 'call', '0x861ec0'),
    (0x0042EB79, 'test', 'byte ptr [rsi + 0x48818], 0x10'),
]


def main():
    d, off = fp.load_image()
    md = Cs(CS_ARCH_X86, CS_MODE_64)
    fails = 0
    for va, mn, ops in CHECKS:
        ins = next(md.disasm(d[off(va):off(va) + 16], va), None)
        ok = ins is not None and ins.mnemonic == mn and ins.op_str == ops
        fails += 0 if ok else 1
        got = "%s %s" % (ins.mnemonic, ins.op_str) if ins else "<no decode>"
        print("%s %08X %s" % ("ok  " if ok else "FAIL", va, got))
    print("FAILS", fails)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
