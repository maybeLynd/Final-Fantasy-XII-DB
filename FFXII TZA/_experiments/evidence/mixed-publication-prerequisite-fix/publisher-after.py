def verify_copied_render_review_links(folder, canonical_home):

    """Relocated render review documents must carry their local referents.



    Scoped to the concrete copied-review defect. This is a pre-copy guard, not

    a replacement for the canonical HEAD-aware link checker or semantic review.

    """

    records=[]

    for doc in sorted(folder.glob('fable-render-*-REVIEW.md')):

        text=doc.read_text(encoding='utf-8')

        for match in re.finditer(r'\[[^\]]*\]\(([^)]+)\)',text):

            target=''.join(match.group(1).split())

            if '://' in target or target.startswith('#'):continue

            if re.search(r'%2f|%5c',target,re.I):raise ValueError('encoded separator in copied render review link')

            target=__import__('urllib.parse',fromlist=['unquote']).unquote(target)

            projected=(canonical_home/target).resolve()

            if not projected.is_relative_to(ROOT.resolve()):raise ValueError('copied render review link outside repository')

            if projected.is_relative_to(canonical_home.resolve()):

                actual=folder/projected.relative_to(canonical_home.resolve())

            else:actual=projected

            if not actual.is_file():raise ValueError('copied render review link unresolved before copying: '+doc.name+' -> '+target)

            records.append(dict(document=doc.name,target=target,sha256=hashlib.sha256(actual.read_bytes()).hexdigest()))

    return dict(status='VERIFIED_COPIED_REVIEW_LINKS' if records else 'NO_COPIED_RENDER_REVIEWS_APPLICABLE',links=records)



